package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

func TestInitWritesTheDetectedGenerateBlockOnce(t *testing.T) {
	t.Parallel()
	ta, _ := surfaceInitApp(t)
	root := checkout(t)
	writeTree(t, root, map[string]string{
		"internal/adapters/inbound/api/handler.go":          "package api\n",
		"internal/adapters/outbound/postgres/plans.go":      "package postgres\n",
		"internal/adapters/outbound/postgres/sqlcgen/db.go": "// Code generated by sqlc. DO NOT EDIT.\n\npackage sqlcgen\n",
	})
	for range 2 {
		if code := ta.run(t.Context(), []string{"init", "--apply", root}); code != exitClean {
			t.Fatalf("exit = %d: %s", code, ta.stderr.String())
		}
	}
	got := readPolicyFile(t, root)
	for _, want := range []string{
		"adapter_sql: internal/adapters/outbound/{package}", "handler: internal/adapters/inbound/{package}",
		"sqlc_out: internal/adapters/outbound/postgres/sqlcgen", "openapi_out: api/gen",
	} {
		if strings.Count(got, "generate:") != 1 || !strings.Contains(got, want) {
			t.Errorf("golaw.yml lacks %q once:\n%s", want, got)
		}
	}
}

func TestInitNamesBothLayoutsAndTheKey(t *testing.T) {
	t.Parallel()
	ta, _ := surfaceInitApp(t)
	root := checkout(t)
	writeTree(t, root, map[string]string{
		"internal/adapters/out/postgres/plans.go":   "package postgres\n",
		"internal/adapters/outbound/meta/client.go": "package meta\n",
	})
	code := ta.run(t.Context(), []string{"init", root})
	if stderr := ta.stderr.String(); code != exitFailure || !strings.Contains(stderr, "internal/adapters/outbound") || !strings.Contains(stderr, "generate.layout.adapter_sql") {
		t.Errorf("exit = %d, stderr %q", code, stderr)
	}
}

func TestInitKeepsAReviewedPolicyWithoutAGenerateBlock(t *testing.T) {
	t.Parallel()
	ta, _ := surfaceInitApp(t)
	root := checkout(t)
	reviewed := renderedPolicy(t)
	if err := os.WriteFile(filepath.Join(root, "golaw.yml"), reviewed, 0o600); err != nil {
		t.Fatal(err)
	}
	if code := ta.run(t.Context(), []string{"init", "--apply", root}); code != exitClean {
		t.Fatalf("exit = %d: %s", code, ta.stderr.String())
	}
	if strings.Contains(readPolicyFile(t, root), "generate:") {
		t.Error("init wrote a generate block into a reviewed policy")
	}
}
