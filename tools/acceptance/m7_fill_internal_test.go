// m7Owned is an owned file as a kind writes it: an open hole after the
// generated names, one import in a block.
const m7Owned = `package postgres

import (
	"context"
)

// ReadPlan reads the plan of one account.
func (x *Plans) ReadPlan(c context.Context, a string) (string, error) {
	// golaw:hole plans.read-plan call x.queries.ReadPlan
	return "", gensupport.Hole("plans.read-plan", c, a)
}
`

func TestM7FillFuncWritesTheBodyUnderTheFillsNames(t *testing.T) {
	t.Parallel()
	fill := m7Fill{
		ID: "plans.read-plan", Recv: "p", Params: []string{"ctx", "account"},
		Body:    "if account == \"\" {\n    return \"\", errors.New(\"no account\")\n}\nreturn p.name(ctx, account), nil\n",
		Imports: []m7Import{{Path: "errors"}, {Path: "context"}},
	}
	got, err := m7FillFunc([]byte(m7Owned), fill)
	if err != nil {
		t.Fatal(err)
	}
	text := string(got)
	for _, want := range []string{
		"func (p *Plans) ReadPlan(ctx context.Context, account string) (string, error) {",
		"\treturn p.name(ctx, account), nil\n",
		"\t\"context\"\n\t\"errors\"\n",
		"// ReadPlan reads the plan of one account.",
	} {
		if !strings.Contains(text, want) {
			t.Fatalf("filled file lacks %q:\n%s", want, text)
		}
	}
	if strings.Contains(text, "golaw:hole") || strings.Contains(text, "gensupport.Hole") || strings.Count(text, "\"context\"") != 1 {
		t.Fatalf("the hole or a duplicate import survived:\n%s", text)
	}
}

func TestM7FillFuncRefusesWhatItCannotPlace(t *testing.T) {
	t.Parallel()
	rows := []struct {
		name string
		fill m7Fill
		want string
	}{
		{"red an id the file does not hold", m7Fill{ID: "plans.archive-plan", Recv: "p", Params: []string{"ctx", "account"}, Body: "return \"\", nil\n"}, "plans.archive-plan"},
		{"red a parameter list of another length", m7Fill{ID: "plans.read-plan", Recv: "p", Params: []string{"ctx"}, Body: "return \"\", nil\n"}, "names 2 parameters, the fill 1"},
		{"red a receiver the method lacks", m7Fill{ID: "plans.read-plan", Params: []string{"ctx", "account"}, Body: "return \"\", nil\n"}, "receiver"},
		{"red a body that does not parse", m7Fill{ID: "plans.read-plan", Recv: "p", Params: []string{"ctx", "account"}, Body: "return (\n"}, "plans.read-plan"},
	}
	for _, row := range rows {
		_, err := m7FillFunc([]byte(m7Owned), row.fill)
		if err == nil || !strings.Contains(err.Error(), row.want) {
			t.Fatalf("%s: error %v, want one naming %q", row.name, err, row.want)
		}
	}
}

func TestM7AddImportsKeepsOneBlock(t *testing.T) {
	t.Parallel()
	rows := []struct {
		name, src, want string
	}{
		{"near no import", "package a\n\nvar V = 1\n", "import (\n\t\"errors\"\n)"},
		{"near a single import", "package a\n\nimport \"context\"\n\nvar V = 1\n", "import (\n\t\"context\"\n\t\"errors\"\n)"},
		{"near the import exists", "package a\n\nimport (\n\t\"errors\"\n)\n\nvar V = errors.New(\"v\")\n", "import (\n\t\"errors\"\n)"},
	}
	for _, row := range rows {
		got, err := m7AddImports([]byte(row.src), []m7Import{{Path: "errors"}})
		if err != nil || !strings.Contains(string(got), row.want) || strings.Count(string(got), "\"errors\"") != 1 {
			t.Fatalf("%s: %v\n%s", row.name, err, got)
		}
	}
	got, err := m7AddImports([]byte("package a\n"), []m7Import{{Name: "apigen", Path: "example.com/slice/api/gen"}})
	if err != nil || !strings.Contains(string(got), "apigen \"example.com/slice/api/gen\"") {
		t.Fatalf("a named import = %v\n%s", err, got)
	}
}

func TestM7ApplyFillsFindsEachHoleOnce(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	m2Write(t, filepath.Join(dir, "internal", "postgres", "plans.go"), m7Owned)
	m2Write(t, filepath.Join(dir, "internal", "postgres", "zz_generated_plans.go"), "// Code generated by golaw 0.7.0 kind=adapter-sql@1; DO NOT EDIT.\npackage postgres\n")
	fill := m7Fill{ID: "plans.read-plan", Recv: "p", Params: []string{"ctx", "account"}, Body: "return account, ctx.Err()\n"}
	if err := m7ApplyFills(dir, []m7Fill{fill}); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(filepath.Join(dir, "internal", "postgres", "plans.go"))
	if err != nil || !strings.Contains(string(body), "return account, ctx.Err()") {
		t.Fatalf("plans.go = %v\n%s", err, body)
	}
	m2Write(t, filepath.Join(dir, "internal", "other", "copy.go"), strings.Replace(m7Owned, "package postgres", "package other", 1))
	m2Write(t, filepath.Join(dir, "internal", "third", "copy.go"), strings.Replace(m7Owned, "package postgres", "package third", 1))
	if err := m7ApplyFills(dir, []m7Fill{fill}); err == nil || !strings.Contains(err.Error(), "2 files") {
		t.Fatalf("a hole in two files = %v", err)
	}
}

func TestM7FillsDecodeTheRecordedFile(t *testing.T) {
	t.Parallel()
	fills, err := m7Fills(testRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	ids := make([]string, 0, len(fills))
	for _, f := range fills {
		if strings.TrimSpace(f.Body) == "" {
			t.Fatalf("fill %s has no body", f.ID)
		}
		ids = append(ids, f.ID)
	}
	sorted := slices.Sorted(slices.Values(ids))
	if len(slices.Compact(sorted)) != len(ids) || len(ids) != 18 {
		t.Fatalf("fill ids = %q", ids)
	}
	dir := t.TempDir()
	m2Write(t, filepath.Join(dir, "tools", "acceptance", "testdata", "gen", "fills.yml.esc"), "- id: a.b\n  body: x\n  extra: y\n")
	if _, err := m7Fills(dir); err == nil {
		t.Fatal("a fill with an unknown key decoded")
	}
}
