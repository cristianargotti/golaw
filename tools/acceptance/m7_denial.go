// The payload keys, the corpus sample and the error texts the M4 and M6
// rows spell as well, named here so the kit's linters count them once.
const (
	m7OldString     = "old_string"
	m7NewString     = "new_string"
	m7ReplaceAll    = "replace_all"
	m7PatchSample   = "pre-apply-patch-add.json"
	m7ThroughClaude = "%s through Claude: %w"
	m7DecodeClaude  = "decode the Claude answer: %w"
)

// m7Denied is a fixture repository with the recorded generator outputs, so
// no generator runs, and every kind written by golaw new and committed.
func (s *m7Suite) m7Denied(ctx context.Context, name string) (string, error) {
	repo, err := s.m7Repository(ctx, name, true)
	if err != nil {
		return "", err
	}
	if err := s.m7NewAll(ctx, repo.dir); err != nil {
		return "", err
	}
	if err := s.m6Commit(ctx, repo.dir, m7NewMessage); err != nil {
		return "", err
	}
	return repo.dir, nil
}

