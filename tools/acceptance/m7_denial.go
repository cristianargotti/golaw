	m7DenialCategory  = "m7-denial"
	m7PortsPath       = "internal/application/growth/ports.go"
	m7ManifestPath    = ".golaw/gen.yml"
	m7VendorPath      = "internal/adapters/out/vendor/stream.go"
	m7GeneratedSuffix = ": edit the contract and the hook regenerates it, or run golaw gen."
	m7GolawFrom       = " is generated by golaw from "
	m7HandwrittenHelp = "golaw:handwritten without a reason: write why after the marker, for example // golaw:handwritten the vendor API streams a chunked body."

