// m7Claude replays f through the Claude hook and answers the reason of a
// red call, nothing for a near miss.
func (s *m7Suite) m7Claude(ctx context.Context, repo string, f fixture, red bool) (string, error) {
	body, err := payload(s.root, repo, f)
	if err != nil {
		return "", err
	}
	got := s.execute(ctx, command{program: s.binary, args: []string{commandHook, agentClaude}, dir: repo, env: s.env, input: string(body)})
	want, _ := m6Wants(red)
	if err := expect(got, want); err != nil {
		return "", fmt.Errorf(m7ThroughClaude, f.name, err)
	}
	if !red {
		return "", nil
	}
	var decoded answer
	if err := json.Unmarshal([]byte(got.stdout), &decoded); err != nil {
		return "", fmt.Errorf(m7DecodeClaude, err)
	}
	return decoded.Hook.Reason, nil
}

