// m7Codex replays the corpus sample with set through the Codex hook and
// answers its reason.
func (s *m7Suite) m7Codex(ctx context.Context, repo, sample string, set map[string]any, red bool) (string, error) {
	body, err := s.m4Sample(agentCodex, sample, repo, set)
	if err != nil {
		return "", err
	}
	got := s.execute(ctx, command{program: s.binary, args: []string{commandHook, agentCodex}, dir: repo, env: s.env, input: string(body)})
	_, want := m6Wants(red)
	reply, err := judgeCodex(eventPre, want, got)
	if err != nil {
		return "", fmt.Errorf("%s through Codex: %w", sample, err)
	}
	return reply.Reason, nil
}

// m7DeletePatch is the apply_patch that deletes path.
func m7DeletePatch(path string) string {
	return strings.Join([]string{"*** Begin Patch", "*** Delete File: " + path, "*** End Patch"}, "\n")
}

// m7Redirect is a shell line that writes the fake's package clause over
// target.
func m7Redirect(target string) string {
	return "echo package ledgertest > " + target
}

// m7JudgeReason holds every agent to one sentence, byte for byte want.
func m7JudgeReason(reasons map[string]string, want string) error {
	if err := m4SameText(m4Reasons, reasons); err != nil {
		return err
	}
	for _, agent := range slices.Sorted(maps.Keys(reasons)) {
		if reasons[agent] != want {
			return fmt.Errorf("%s gave the reason %q, want %q: %w", agent, reasons[agent], want, ErrAcceptance)
		}
	}
	return nil
}

// m7JudgeGenerated holds a reason to the shape of a golaw regenerable
// file's denial: the path, a contract and the fix. Which contract of the
// entry comes first is the guard's choice, so the row holds the shape.
func m7JudgeGenerated(reason, path string) error {
	contract, found := strings.CutPrefix(reason, path+m7GolawFrom)
	if found {
		contract, found = strings.CutSuffix(contract, m7GeneratedSuffix)
	}
	if !found || strings.TrimSpace(contract) == "" {
		return fmt.Errorf("the reason %q does not name %s, its contract and the fix %q: %w", reason, path, m7GeneratedSuffix, ErrAcceptance)
	}
	return nil
}
