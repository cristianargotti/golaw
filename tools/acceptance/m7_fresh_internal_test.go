func TestM7JudgeHolesOpenWantsOnlyTheRedTestsAndTheCheck(t *testing.T) {
	t.Parallel()
	ids := []string{"plans.read-plan", "readplan.execute"}
	tests := "--- FAIL: TestPlansReadPlan\n    hole plans.read-plan is open: call p.queries.ReadPlan\n" +
		"--- FAIL: TestReadPlanExecute\n    hole readplan.execute is open: call the ledger\n"
	made := result{code: 2, stdout: tests, stderr: "make: *** [golaw.mk:44: test] Error 1\nmake: *** [golaw.mk:40: generate-check] Error 1\n"}
	checked := result{code: 1, stdout: "golaw gen --check: hole open internal/adapters/out/postgres/plans.go:41 plans.read-plan: fill it and its red test\n" +
		"golaw gen --check: hole open internal/application/growth/read_plan.go:22 readplan.execute: fill it and its red test\n"}
	rows := []struct {
		name          string
		made, checked result
		ok            bool
	}{
		{"near the red tests and the check", made, checked, true},
		{"red make passed", result{stdout: tests}, checked, false},
		{"red lint failed too", result{code: 2, stdout: tests, stderr: made.stderr + "make: *** [golaw.mk:33: lint] Error 1\n"}, checked, false},
		{"red the check target did not fail", result{code: 2, stdout: tests, stderr: "make: *** [golaw.mk:44: test] Error 1\n"}, checked, false},
		{"red a hole without its red test", result{code: 2, stdout: strings.SplitAfter(tests, "\n")[0] + strings.SplitAfter(tests, "\n")[1], stderr: made.stderr}, checked, false},
		{"red the check passed", made, result{stdout: "golaw gen --check: clean, 0 drift, 0 open holes\n"}, false},
		{"red the check names one hole", made, result{code: 1, stdout: strings.SplitAfter(checked.stdout, "\n")[0]}, false},
	}
	for _, row := range rows {
		if err := m7JudgeHolesOpen(row.made, row.checked, ids); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
	// Near row: the seed hole of an SQL adapter lives in its integration
	// test, which make ci never builds; the check names it, no red test runs.
	seeded := checked
	seeded.stdout += "golaw gen --check: hole open internal/adapters/out/postgres/plans_integration_test.go:8 seed.plans: fill it and its red test\n"
	if err := m7JudgeHolesOpen(made, seeded, append(slices.Clone(ids), "seed.plans")); err != nil {
		t.Fatalf("an integration seed hole: %v", err)
	}
}

func TestM7DigestCoversTheGolawRegenerableFilesOnly(t *testing.T) {
	t.Parallel()
	header := "// Code generated by golaw 0.7.0 kind=port@1; DO NOT EDIT.\n\npackage ledgertest\n"
	write := func(dir string, order []string) {
		files := map[string]string{
			"internal/application/growth/ledgertest/zz_generated_fake.go":  header + "type Fake struct{}\n",
			"internal/application/growth/ledgertest/zz_generated_suite.go": header + "func Run() {}\n",
			"internal/application/growth/ledgertest/cases.go":              "package ledgertest\n",
			"internal/adapters/out/postgres/sqlcgen/zz_generated_other.go": "// Code generated by sqlc. DO NOT EDIT.\npackage sqlcgen\n",
		}
		for _, path := range order {
			m2Write(t, filepath.Join(dir, filepath.FromSlash(path)), files[path])
		}
	}
	paths := []string{
		"internal/application/growth/ledgertest/zz_generated_fake.go", "internal/application/growth/ledgertest/zz_generated_suite.go",
		"internal/application/growth/ledgertest/cases.go", "internal/adapters/out/postgres/sqlcgen/zz_generated_other.go",
	}
	first, second := t.TempDir(), t.TempDir()
	write(first, paths)
	reversed := slices.Clone(paths)
	slices.Reverse(reversed)
	write(second, reversed)
	a, n, err := m7Digest(first)
	if err != nil || n != 2 || len(a) != 64 {
		t.Fatalf("digest = %q over %d files: %v", a, n, err)
	}
	if b, _, err := m7Digest(second); err != nil || b != a {
		t.Fatalf("the digest depends on the write order: %q %q %v", a, b, err)
	}
	m2Write(t, filepath.Join(first, "internal", "application", "growth", "ledgertest", "zz_generated_fake.go"), strings.ReplaceAll(header, "\n", "\r\n"))
	if _, _, err := m7Digest(first); err == nil {
		t.Fatal("a regenerable file with CRLF line endings passed")
	}
	if _, n, err := m7Digest(t.TempDir()); err == nil || n != 0 {
		t.Fatal("a tree without a regenerable file passed")
	}
}

func TestM7JudgeDuplicationReadsTheMarker(t *testing.T) {
	t.Parallel()
	rows := []struct {
		name, output string
		ok           bool
	}{
		{"near under the threshold", "=== RUN   TestM7Duplication\n    m7_duplication_internal_test.go:52: M7_DUPLICATION 0.80\n--- PASS\n", true},
		{"near a bare marker", "M7_DUPLICATION 0.00\n", true},
		{"red at the threshold", "    m7_duplication_internal_test.go:52: M7_DUPLICATION 1.50\n", false},
		{"red no marker", "--- SKIP: TestM7Duplication\n", false},
		{"red a marker without a number", "M7_DUPLICATION many\n", false},
	}
	for _, row := range rows {
		if err := m7JudgeDuplication(row.output); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
}

