func TestM7JudgeCoverageWantsEightyOnNewCode(t *testing.T) {
	t.Parallel()
	rows := []struct {
		name string
		got  result
		ok   bool
	}{
		{"near the floor reached", result{stdout: "new code coverage 82.4% (412 of 500 lines) against 1a2b3c\n"}, true},
		{"near exactly eighty", result{stdout: "new code coverage 80.0% (400 of 500 lines)\n"}, true},
		{"red under the floor", result{stdout: "new code coverage 79.9% (399 of 500 lines)\n", code: 1}, false},
		{"red a passing exit under the floor", result{stdout: "new code coverage 61.0%\n"}, false},
		{"red unmeasured", result{code: 2, stderr: "golaw: the report is older than internal/a.go\n"}, false},
		{"red no number", result{stdout: "new code coverage\n"}, false},
	}
	for _, row := range rows {
		if err := m7JudgeCoverage(row.got); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
	if got, ok := m7Percent("a 12% then 90.5%"); !ok || got != 12 {
		t.Fatalf("m7Percent = %v %v, want the first number", got, ok)
	}
}

