// The bytes the denial rows write: a hand written package clause over the
// fake, the manifest's first line, the plan file of the area and the owned
// half of the SQL adapter, and the two forms of the handwritten marker.
const (
	m7FakeClause    = "package ledgertest\n"
	m7ManifestBytes = "golaw-gen: 1\n"
	m7PlanPath      = "internal/application/growth/plan.go"
	m7OwnedPlans    = "internal/adapters/out/postgres/plans.go"
	m7BareMarker    = "// golaw:handwritten\npackage vendor\n"
	m7ReasonMarker  = "// golaw:handwritten the vendor API streams a chunked body\npackage vendor\n"
	m7QuotedHeader  = `const quoted = "// Code generated by golaw 0.7.0 kind=port@1; DO NOT EDIT."` + "\n"
	m7TargetLine    = `"$TARGET"`
	m7GolawGen      = "golaw gen"
)

// m7DenialCases are the m7-denial rows in report order; each builds its own
// repository and none needs a generator.
func m7DenialCases() []m7Case {
	fake := func(run func(*m7Suite, context.Context, string) (map[string]string, error)) func(*m7Suite, context.Context) error {
		return m7DenyRow(run, m7FakeReason)
	}
	return []m7Case{
		{name: "claude-write", run: fake(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return m7One(agentClaude)(s.m6ClaudeWrite(ctx, repo, m7FakePath, []byte(m7FakeClause), true))
		})},
		{name: "claude-edit", run: fake((*m7Suite).m7EditFake)},
		{name: "claude-redirect", run: fake(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return m7One(agentClaude)(s.m7ClaudeShell(ctx, repo, m7Redirect(m7FakePath), true))
		})},
		{name: "codex-update", run: fake(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return m7One(agentCodex)(s.m6CodexWrite(ctx, repo, m7FakePath, []byte(m7FakeClause), true))
		})},
		{name: "codex-delete", run: fake(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return m7One(agentCodex)(s.m7CodexPatch(ctx, repo, m7DeletePatch(m7FakePath), true))
		})},
		{name: "codex-redirect", run: fake(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return m7One(agentCodex)(s.m7CodexShell(ctx, repo, m7Redirect(m7FakePath), true))
		})},
		{name: "cursor-feedback", run: (*m7Suite).m7CursorFeedback},
		{name: "third-party", run: m7DenyRow(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return s.m6Agents(ctx, repo, m7QueriesPath, []byte("package sqlcgen\n"), true, false)
		}, m7QueriesReason)},
		{name: "header-stripped", run: (*m7Suite).m7HeaderStripped},
		{name: "manifest-write", run: m7DenyRow(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return s.m6Agents(ctx, repo, m7ManifestPath, []byte(m7ManifestBytes), true, false)
		}, m7ManifestReason)},
		{name: "handwritten-bare", run: m7DenyRow(func(s *m7Suite, ctx context.Context, repo string) (map[string]string, error) {
			return m7One(agentClaude)(s.m6ClaudeWrite(ctx, repo, m7VendorPath, []byte(m7BareMarker), true))
		}, m7BareReason)},
		{name: "near-misses", run: (*m7Suite).m7NearMisses},
	}
}

// m7DenyRow is a row that writes through the agents in a repository of its
// own and holds every reason to want.
func m7DenyRow(run func(*m7Suite, context.Context, string) (map[string]string, error), want string) func(*m7Suite, context.Context) error {
	return func(s *m7Suite, ctx context.Context) error {
		repo, err := s.m7Denied(ctx, "denial")
		if err != nil {
			return err
		}
		reasons, err := run(s, ctx, repo)
		if err != nil {
			return err
		}
		return m7JudgeReason(reasons, want)
	}
}

// m7One keys the reason of one agent's call by the agent.
func m7One(agent string) func(string, error) (map[string]string, error) {
	return func(reason string, err error) (map[string]string, error) {
		if err != nil {
			return nil, err
		}
		return map[string]string{agent: reason}, nil
	}
}

// m7EditFake is Claude's Edit of the fake's first line.
func (s *m7Suite) m7EditFake(ctx context.Context, repo string) (map[string]string, error) {
	body, _, err := m6Before(repo, m7FakePath)
	if err != nil {
		return nil, err
	}
	first, _, _ := strings.Cut(string(body), "\n")
	return m7One(agentClaude)(s.m7ClaudeEdit(ctx, repo, m7FakePath, first, strings.TrimSuffix(m7HandEdit, "\n"), true))
}

// m7CursorFeedback: Cursor's write of the fake is allowed before it runs,
// as Cursor cannot be denied a write (A4), and fed back after it with the
// path and the command that renders the file again.
func (s *m7Suite) m7CursorFeedback(ctx context.Context) error {
	repo, err := s.m7Denied(ctx, "cursor-feedback")
	if err != nil {
		return err
	}
	before, existed, err := m6Before(repo, m7FakePath)
	if err != nil {
		return err
	}
	fed, err := s.m6CursorWrite(ctx, repo, m7FakePath, []byte(m7FakeClause), true)
	if err != nil {
		return err
	}
	if !strings.Contains(fed, m7FakePath) || !strings.Contains(fed, m7GolawGen) {
		return fmt.Errorf("cursor's feedback %q lacks %s and %s: %w", fed, m7FakePath, m7GolawGen, ErrAcceptance)
	}
	return m6Restore(repo, m7FakePath, before, existed)
}

// m7HeaderStripped: a patch that drops the header of a regenerable file is
// still denied, recognized by the manifest path (M7.9.2).
func (s *m7Suite) m7HeaderStripped(ctx context.Context) error {
	repo, err := s.m7Denied(ctx, "header-stripped")
	if err != nil {
		return err
	}
	body, _, err := m6Before(repo, m7PlansPath)
	if err != nil {
		return err
	}
	_, rest, _ := bytes.Cut(body, []byte("\n"))
	reason, err := s.m6CodexWrite(ctx, repo, m7PlansPath, rest, true)
	if err != nil {
		return err
	}
	return m7JudgeGenerated(reason, m7PlansPath)
}

// m7NearMisses are the writes the guard must allow, each a false denial
// when refused: a header quoted in a body (A47), an owned file of the same
// entry, a shell target that is not literal (A46) and a marker with its
// reason (A53).
func (s *m7Suite) m7NearMisses(ctx context.Context) error {
	repo, err := s.m7Denied(ctx, "near-misses")
	if err != nil {
		return err
	}
	plan, _, err := m6Before(repo, m7PlanPath)
	if err != nil {
		return err
	}
	owned, _, err := m6Before(repo, m7OwnedPlans)
	if err != nil {
		return err
	}
	steps := []func() (string, error){
		func() (string, error) {
			return s.m6ClaudeWrite(ctx, repo, m7PlanPath, append(plan, m7QuotedHeader...), false)
		},
		func() (string, error) {
			return s.m6CodexWrite(ctx, repo, m7OwnedPlans, append(owned, m7HandEdit...), false)
		},
		func() (string, error) { return s.m7ClaudeShell(ctx, repo, m7Redirect(m7TargetLine), false) },
		func() (string, error) { return s.m7CodexShell(ctx, repo, m7Redirect(m7TargetLine), false) },
		func() (string, error) { return s.m6ClaudeWrite(ctx, repo, m7VendorPath, []byte(m7ReasonMarker), false) },
	}
	for _, step := range steps {
		if _, err := step(); err != nil {
			return err
		}
	}
	return nil
}
