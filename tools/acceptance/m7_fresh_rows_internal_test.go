// m7Rendered is what the seven commands write over the fixture, rendered
// in process, so a scripted golaw new leaves the holes the fills close.
func m7Rendered(t *testing.T) map[string][]byte {
	t.Helper()
	base := gentest.Contracts()
	repo, err := m7Fixture(testRoot(t), m7RepoDir)
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range m7BillingFiles() {
		base[path] = repo[path]
	}
	report := goldentest.Run(t, goldentest.Slice{
		Name: "acceptance-rows", Module: "example.com/slice", Base: base, Kinds: kinds.All(), Commands: m7GoldenCommands(),
	}, goldentest.StepLaws)
	return maps.Clone(report.Files)
}

// m7FreshSuite is an M7 suite whose surface tools count as installed and
// whose make is a simulated program the replies name.
func m7FreshSuite(t *testing.T) *m7Suite {
	t.Helper()
	s := newM7Suite(m2TestSuite(t))
	s.shared.tried = true
	s.m2.Make = filepath.Join(s.base, "simulated", executable("make"))
	return s
}

// m7PipelineReplies answer the steps of a fresh repository as a pipeline
// that agrees with it; the replies a test puts first win.
func m7PipelineReplies(t *testing.T, s *m7Suite, rendered map[string][]byte, ids []string) []m5Reply {
	t.Helper()
	var opened, checked strings.Builder
	for _, id := range ids {
		fmt.Fprintf(&opened, "--- FAIL\n    hole %s is open: fill it\n", id)
		fmt.Fprintf(&checked, "golaw gen --check: hole open internal/a.go:1 %s: fill it and its red test\n", id)
	}
	writeKinds := func(t *testing.T, c command) {
		t.Helper()
		if c.args[2] == m7Commands()[0].name {
			if err := m6WriteFiles(c.dir, rendered); err != nil {
				t.Fatal(err)
			}
		}
	}
	writeOutputs := func(t *testing.T, c command) {
		t.Helper()
		m2Write(t, filepath.Join(c.dir, "api", "gen", "server.gen.go"), "// Code generated by oapi-codegen. DO NOT EDIT.\npackage gen\n")
		m2Write(t, filepath.Join(c.dir, filepath.FromSlash(m7QueriesPath)), "// Code generated by sqlc. DO NOT EDIT.\npackage sqlcgen\n")
	}
	return []m5Reply{
		m6InitReply(),
		{program: s.goTool, prefix: []string{"mod", "tidy"}, answer: m5Answer(result{})},
		{prefix: []string{"gen", "--check"}, answer: m5Answer(result{code: 1, stdout: checked.String()})},
		{prefix: []string{"gen"}, answer: m5After(writeOutputs, result{})},
		{prefix: []string{"new"}, answer: m5After(writeKinds, result{})},
		{program: s.m2.Make, prefix: []string{"fmt"}, answer: m5Answer(result{})},
		{program: s.m2.Make, prefix: []string{"-k", "ci"}, answer: m5Answer(result{
			code: 2, stdout: opened.String(),
			stderr: "make: *** [golaw.mk:44: test] Error 1\nmake: *** [golaw.mk:40: generate-check] Error 1\n",
		})},
		{program: s.m2.Make, prefix: []string{"ci"}, answer: m5Answer(result{})},
		{program: s.goTool, prefix: []string{"test", "-coverprofile"}, answer: m5Answer(result{})},
		{prefix: []string{"coverage", "--new-code"}, answer: m5Answer(result{stdout: "new code coverage 91.0%\n"})},
		{program: s.goTool, prefix: []string{"test", "-run"}, answer: m5Answer(result{stdout: m7DupMarker + " 0.40\n"})},
	}
}

// m7FillIDsOf are the ids of the recorded fills.
func m7FillIDsOf(t *testing.T) []string {
	t.Helper()
	ids, err := m7FillIDs(testRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	return ids
}

func TestM7FreshRowsPassOverAPipelineThatAgrees(t *testing.T) {
	t.Parallel()
	s := m7FreshSuite(t)
	ids := m7FillIDsOf(t)
	s.execute = m5Script(t, s.suite, m7PipelineReplies(t, s, m7Rendered(t), ids)...).Execute
	for _, c := range m7FreshCases() {
		if err := c.run(s.m7Scope(m7FreshCategory, c.name), t.Context()); err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
	}
	if !strings.HasPrefix(s.gen.note, "rendering digest ") || !strings.HasSuffix(s.gen.note, " files") {
		t.Fatalf("the digest row noted %q", s.gen.note)
	}
	if !s.gen.filledTried || s.gen.filled == nil || s.gen.filled.base == "" {
		t.Fatalf("the fresh repository was not memoized: %+v", s.gen)
	}
}

// TestM7FreshRowsNameTheStepThatFailed: each step a row takes stops it
// with the step named, and a missing tool skips it with the cause.
func TestM7FreshRowsNameTheStepThatFailed(t *testing.T) {
	t.Parallel()
	rendered, ids := m7Rendered(t), m7FillIDsOf(t)
	refuse := func(program string, prefix ...string) func(*m7Suite) m5Reply {
		return func(s *m7Suite) m5Reply {
			switch program {
			case "go":
				program = s.goTool
			case "make":
				program = s.m2.Make
			}
			return m5Reply{program: program, prefix: prefix, answer: m5Answer(result{code: 2, stderr: "refused\n"})}
		}
	}
	for _, tc := range []struct {
		name, row, want string
		first           func(*m7Suite) m5Reply
	}{
		{"red the tools module untidy", "ci-green", "tidy the module", refuse("go", "mod", "tidy")},
		{"red golaw gen refused", "new-code", "generate the third party outputs of fresh", refuse("", "gen")},
		{"red golaw new refused", "duplication", "golaw new usecase", refuse("", "new")},
		{"red the fills unformatted", "rendering-digest", "format the fills of fresh", refuse("make", "fmt")},
		{"red make ci", "ci-green", "make ci of the filled repository", refuse("make", "ci")},
		{"red the profile unwritten", "new-code", "write the coverage profile", refuse("go", "test", "-coverprofile")},
		{"red coverage unmeasured", "new-code", "golaw coverage --new-code", refuse("", "coverage")},
		{"red the measure refused", "duplication", "measure the duplication", refuse("go", "test", "-run")},
		{"red the holes repository refused", "holes-open", "generate the third party outputs of holes", refuse("", "gen")},
	} {
		s := m7FreshSuite(t)
		replies := append([]m5Reply{tc.first(s)}, m7PipelineReplies(t, s, rendered, ids)...)
		s.execute = m5Script(t, s.suite, replies...).Execute
		err := m7RunFresh(t, s, tc.row)
		if !errors.Is(err, ErrAcceptance) || !strings.Contains(err.Error(), tc.want) {
			t.Fatalf("%s: %v, want an error naming %q", tc.name, err, tc.want)
		}
	}
}

// m7RunFresh runs one fresh row by name in its scope.
func m7RunFresh(t *testing.T, s *m7Suite, name string) error {
	t.Helper()
	for _, c := range m7FreshCases() {
		if c.name == name {
			return c.run(s.m7Scope(m7FreshCategory, c.name), t.Context())
		}
	}
	t.Fatalf("no fresh row %s", name)
	return nil
}

func TestM7MakeCISkipsWithoutTheToolsThePipelineInstalls(t *testing.T) {
	t.Parallel()
	s := m7FreshSuite(t)
	s.shared.err = ErrAcceptance
	if _, err := s.m7MakeCI(t.Context(), m7Repo{dir: t.TempDir()}); !strings.HasPrefix(m7SkipCause(err), m6ToolsSkipped) {
		t.Fatalf("without the surface tools = %v", err)
	}
	s = m7FreshSuite(t)
	s.lookup = func(name string) (string, error) { return "", fmt.Errorf("%s not found: %w", name, ErrAcceptance) }
	if _, err := s.m7MakeCI(t.Context(), m7Repo{dir: t.TempDir()}); !strings.HasPrefix(m7SkipCause(err), m7Redocly+" unavailable") {
		t.Fatalf("without redocly = %v", err)
	}
}

// m7SkipCause is the cause of a skip, or nothing for any other answer.
func m7SkipCause(err error) string {
	if skipped, ok := errors.AsType[*m7Skipped](err); ok {
		return skipped.cause
	}
	return ""
}
