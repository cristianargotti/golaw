// TestM7ReasonsAreTheAddendumLines holds every agent reason to the bytes of
// the M7.9.6 table for the paths of the fixture repository.
func TestM7ReasonsAreTheAddendumLines(t *testing.T) {
	t.Parallel()
	rows := map[string]string{
		m7FakeReason:     "internal/application/growth/ledgertest/zz_generated_fake.go is generated by golaw from internal/application/growth/ports.go (port Ledger): edit the contract and the hook regenerates it, or run golaw gen.",
		m7QueriesReason:  "internal/adapters/out/postgres/sqlcgen/plans.sql.go is generated by sqlc from db/queries/plans.sql: edit the query and run golaw gen.",
		m7ManifestReason: ".golaw/gen.yml is written only by the golaw CLI: run golaw new <kind> <name> or golaw gen.",
		m7BareReason:     "internal/adapters/out/vendor/stream.go:1 adds golaw:handwritten without a reason: write why after the marker, for example // golaw:handwritten the vendor API streams a chunked body.",
	}
	for got, want := range rows {
		if got != want {
			t.Fatalf("reason %q, want %q", got, want)
		}
	}
}

func TestM7PatchAndRedirectShapes(t *testing.T) {
	t.Parallel()
	if got := m7DeletePatch(m7FakePath); got != "*** Begin Patch\n*** Delete File: "+m7FakePath+"\n*** End Patch" {
		t.Fatalf("delete patch = %q", got)
	}
	if got := m7Redirect(m7FakePath); got != "echo package ledgertest > "+m7FakePath {
		t.Fatalf("redirection = %q", got)
	}
	if got := m7Redirect(`"$TARGET"`); got != `echo package ledgertest > "$TARGET"` {
		t.Fatalf("variable redirection = %q", got)
	}
}

func TestM7JudgeReasonWantsOneSentenceOnEveryAgent(t *testing.T) {
	t.Parallel()
	rows := []struct {
		name    string
		reasons map[string]string
		ok      bool
	}{
		{"near both agents", map[string]string{agentClaude: m7FakeReason, agentCodex: m7FakeReason}, true},
		{"red another sentence", map[string]string{agentClaude: m7FakeReason + " ", agentCodex: m7FakeReason + " "}, false},
		{"red the agents differ", map[string]string{agentClaude: m7FakeReason, agentCodex: m7QueriesReason}, false},
		{"red an empty reason", map[string]string{agentClaude: ""}, false},
	}
	for _, row := range rows {
		if err := m7JudgeReason(row.reasons, m7FakeReason); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
}

func TestM7JudgeGeneratedNamesThePathAndTheFix(t *testing.T) {
	t.Parallel()
	good := m7PlansPath + " is generated by golaw from internal/application/growth/ports.go (port Ledger)" + m7GeneratedSuffix
	rows := []struct {
		name, reason string
		ok           bool
	}{
		{"near the port contract named", good, true},
		{"near the query contract named", m7PlansPath + " is generated by golaw from db/queries/plans.sql" + m7GeneratedSuffix, true},
		{"red another path", m7FakeReason, false},
		{"red no fix", m7PlansPath + " is generated by golaw from internal/application/growth/ports.go (port Ledger).", false},
		{"red no contract", m7PlansPath + " is generated by golaw from " + m7GeneratedSuffix, false},
	}
	for _, row := range rows {
		if err := m7JudgeGenerated(row.reason, m7PlansPath); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
}

func TestM7DenialCasesAreInTheCatalog(t *testing.T) {
	t.Parallel()
	want := []string{
		"claude-write", "claude-edit", "claude-redirect", "codex-update", "codex-delete", "codex-redirect",
		"cursor-feedback", "third-party", "header-stripped", "manifest-write", "handwritten-bare", "near-misses",
	}
	for _, catalog := range m7Catalogs() {
		if catalog.category == m7DenialCategory {
			if got := m7Names(catalog.cases); !slices.Equal(got, want) {
				t.Fatalf("m7-denial rows = %q", got)
			}
			return
		}
	}
	t.Fatal("m7Catalogs lacks m7-denial")
}
