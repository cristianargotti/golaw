// TestM3BirthFixtureKeepsTheSurveyShapes pins each shape of a template
// birth the M3 tasks reproduce, so a later edit of the fixture cannot drop
// the case a task proves.
func TestM3BirthFixtureKeepsTheSurveyShapes(t *testing.T) {
	t.Parallel()
	files, err := m3BirthFiles(testRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	for _, shape := range []struct{ path, fragment string }{
		{"Makefile", "GOBIN=$(shell go env GOPATH)/bin"},
		{"Makefile", "else ifneq (,$(filter live,$(MAKECMDGOALS)))"},
		{"Makefile", "\nlint:\n"},
		{"Makefile", "\ntest:\n"},
		{".golangci.yml", "version: 2\n"},
		{".golangci.yml", "linters-settings:"},
		{".editorconfig", "[*.go]\nindent_style = tab\n"},
		{".github/CODEOWNERS", ".github/ @example-org/platform-team"},
		{"Dockerfile", "FROM golang:1.27-alpine AS build"},
		{"Dockerfile", "FROM registry.example.test/platform/certificates:latest AS certs"},
		{"api/swagger.yaml", "swagger: \"2.0\""},
		{"api/docs.go", "// Package api Code generated by swaggo/swag. DO NOT EDIT\n"},
		{"go.mod", "github.com/spf13/cobra v1.10.2 // indirect"},
		{"main.go", "\"github.com/spf13/cobra\""},
		{"main_test.go", "\"github.com/stretchr/testify/assert\""},
	} {
		if !strings.Contains(string(files[shape.path]), shape.fragment) {
			t.Errorf("%s lost the shape %q", shape.path, shape.fragment)
		}
	}
	if strings.Contains(string(files[".editorconfig"]), "[Makefile]") {
		t.Error("the birth .editorconfig must lack a [Makefile] section")
	}
	dir := t.TempDir()
	if err = m3WriteBirth(testRoot(t), dir); err != nil {
		t.Fatal(err)
	}
	written, err := os.ReadFile(filepath.Join(dir, ".github", "CODEOWNERS"))
	if err != nil || !bytes.Equal(written, files[".github/CODEOWNERS"]) {
		t.Fatalf("written CODEOWNERS = %q, %v", written, err)
	}
}

func TestM3BirthFilesRefusesAFileWithoutTheSuffix(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := filepath.Join(root, filepath.FromSlash(m3BirthDir))
	checkedWrite(t, filepath.Join(dir, "go.mod.txt"), "module example.test/birth\n")
	if files, err := m3BirthFiles(root); err != nil || string(files["go.mod"]) != "module example.test/birth\n" {
		t.Fatalf("near fixture = %v, %v", files, err)
	}
	checkedWrite(t, filepath.Join(dir, "Makefile"), "all:\n")
	if _, err := m3BirthFiles(root); !errors.Is(err, ErrAcceptance) {
		t.Fatalf("a file without the suffix = %v", err)
	}
	if _, err := m3BirthFiles(t.TempDir()); err == nil {
		t.Fatal("an absent fixture must fail")
	}
}
