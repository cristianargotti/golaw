func TestM7HubTreeHasTheHubLayout(t *testing.T) {
	t.Parallel()
	tree := m7HubTree(false)
	count := func(prefix string) int {
		n := 0
		for path := range tree {
			if strings.HasPrefix(path, prefix) && strings.HasSuffix(path, ".go") {
				n++
			}
		}
		return n
	}
	if count("internal/adapters/in/") != m7InboundCount || count("internal/adapters/out/") != m7OutboundCount {
		t.Fatalf("tree = %d inbound, %d outbound", count("internal/adapters/in/"), count("internal/adapters/out/"))
	}
	for path, body := range tree {
		if strings.HasPrefix(path, "internal/adapters/outbound/") && !strings.HasPrefix(string(body), "// Code generated by sqlc. DO NOT EDIT.") {
			t.Fatalf("%s is hand written in the generated only outbound tree", path)
		}
	}
	if len(m7HubTree(true)) != len(tree)+1 {
		t.Fatal("the ambiguous tree does not add one hand written outbound adapter")
	}
}

func TestM7JudgeLayoutWantsTheDetectedPaths(t *testing.T) {
	t.Parallel()
	good := "generate:\n  layout:\n    port: internal/application/{area}\n    usecase: internal/application/{area}\n" +
		"    adapter_sql: internal/adapters/out/{package}\n    adapter_http: internal/adapters/out/{package}\n" +
		"    handler: internal/adapters/in/{package}\n    wiring: cmd/{main}\n  support: internal/gensupport\n" +
		"  third_party:\n    sqlc_out: internal/adapters/out/postgres/sqlcgen\n    openapi: api/openapi.yaml\n    openapi_out: api/gen\n"
	rows := []struct {
		name, policy string
		ok           bool
	}{
		{"near the detected layout", good, true},
		{"red the generated tree chosen", strings.ReplaceAll(good, "adapters/out/", "adapters/outbound/"), false},
		{"red the old sqlc output", strings.Replace(good, "sqlc_out: internal/adapters/out/postgres/sqlcgen", "sqlc_out: internal/adapters/outbound/postgres/sqlcgen", 1), false},
		{"red no generate block", "golaw: 1\n", false},
	}
	for _, row := range rows {
		if err := m7JudgeLayout([]byte(row.policy)); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
}

func TestM7JudgeAmbiguousWantsBothCandidatesAndTheKey(t *testing.T) {
	t.Parallel()
	named := "golaw: two layouts hold hand written adapters: internal/adapters/out and internal/adapters/outbound: set generate.layout.adapter_sql in golaw.yml\n"
	rows := []struct {
		name string
		got  result
		ok   bool
	}{
		{"near both named", result{code: 2, stderr: named}, true},
		{"red a silent choice", result{}, false},
		{"red one candidate", result{code: 2, stderr: "golaw: internal/adapters/out holds adapters: set generate.layout.adapter_sql\n"}, false},
		{"red no key", result{code: 2, stderr: "golaw: internal/adapters/out and internal/adapters/outbound\n"}, false},
	}
	for _, row := range rows {
		if err := m7JudgeAmbiguous(row.got); (err == nil) != row.ok {
			t.Fatalf("%s: %v", row.name, err)
		}
	}
}

func TestM7LayoutCasesAreInTheCatalog(t *testing.T) {
	t.Parallel()
	got := map[string][]string{}
	for _, catalog := range m7Catalogs() {
		got[catalog.category] = m7Names(catalog.cases)
	}
	if !slices.Equal(got[m7LayoutCategory], []string{"detected-layout", "ambiguous-layout"}) ||
		!slices.Equal(got[m7MapCategory], []string{"budget", "holes-first"}) {
		t.Fatalf("catalog = %q", got)
	}
}
