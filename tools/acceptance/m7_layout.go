// The layout rows of M7.13 row 7, and the sizes of the hub the fixture
// copies: the survey counts its 5 inbound and 11 outbound adapter packages.
const (
	m7LayoutCategory = "m7-layout"
	m7InboundCount   = 5
	m7OutboundCount  = 11
)

// m7HubModule is the go.mod of the hub sized fixtures.
const m7HubModule = "module example.com/hub\n\ngo 1.27\n"

// m7Adapter is one hand written adapter package of the hub fixture.
func m7Adapter(pkg string) []byte {
	return []byte("// Package " + pkg + " is an adapter of the fixture.\npackage " + pkg + "\n\n// Name names the adapter.\nconst Name = \"" + pkg + "\"\n")
}

// m7HubTree is a repository shaped as the hub: hand written adapters under
// adapters/in and adapters/out, and an adapters/outbound that holds only
// generator output, the tree the fixed sqlc path left behind (survey 1.1).
// With ambiguous, outbound also holds a hand written adapter, so init
// cannot place the outbound kinds without guessing.
func m7HubTree(ambiguous bool) map[string][]byte {
	tree := map[string][]byte{
		"go.mod": []byte(m7HubModule),
		"internal/application/growth/ports.go": []byte("// Package growth holds the port of the fixture.\npackage growth\n\n" +
			"// Ledger reads one value.\ntype Ledger interface {\n\t// Read reads the value.\n\tRead() string\n}\n"),
		"internal/adapters/outbound/postgres/sqlcgen/db.go": []byte("// Code generated by sqlc. DO NOT EDIT.\n\npackage sqlcgen\n"),
	}
	for i := range m7InboundCount {
		pkg := fmt.Sprintf("in%d", i)
		tree["internal/adapters/in/"+pkg+"/adapter.go"] = m7Adapter(pkg)
	}
	for i := range m7OutboundCount {
		pkg := fmt.Sprintf("out%d", i)
		tree["internal/adapters/out/"+pkg+"/adapter.go"] = m7Adapter(pkg)
	}
	if ambiguous {
		tree["internal/adapters/outbound/legacy/adapter.go"] = m7Adapter("legacy")
	}
	return tree
}

// m7Adopted writes files into a repository of its own and runs init over
// them; it answers the init result as it came, so a row judges a refused
// init as well as a written policy, and an error only for a step before.
func (s *m7Suite) m7Adopted(ctx context.Context, name, capabilities string, files map[string][]byte) (string, result, error) {
	dir := filepath.Join(s.base, dirRepos, name)
	if err := m6WriteFiles(dir, files); err != nil {
		return "", result{}, err
	}
	if err := s.gitSteps(ctx, dir, []string{commandInit, m2Quiet}, m7LongPaths()); err != nil {
		return "", result{}, err
	}
	return dir, s.m5Golaw(ctx, dir, commandInit, m5CapabilitiesFlag, capabilities, flagApply), nil
}

// m7JudgeLayout requires the paths the hand written adapters of the hub
// tree use, and no path under the generated only outbound tree.
func m7JudgeLayout(policy []byte) error {
	text := string(policy)
	for _, want := range []string{
		"adapter_sql: internal/adapters/out/{package}",
		"adapter_http: internal/adapters/out/{package}",
		"handler: internal/adapters/in/{package}",
		"sqlc_out: internal/adapters/out/postgres/sqlcgen",
	} {
		if !strings.Contains(text, want) {
			key, _, _ := strings.Cut(want, ":")
			return fmt.Errorf("the generate block lacks %s of the detected layout (%q): %w", key, want, ErrAcceptance)
		}
	}
	if strings.Contains(text, "adapters/outbound") {
		return fmt.Errorf("the generate block names the generated only adapters/outbound: %w", ErrAcceptance)
	}
	return nil
}

// m7OutAlone matches adapters/out named on its own, not only inside
// adapters/outbound.
var m7OutAlone = regexp.MustCompile(`internal/adapters/out\b`)

// m7JudgeAmbiguous requires a refusal that names both candidates and the
// key that settles them, because a silent choice is what M7.6.2 forbids.
func m7JudgeAmbiguous(got result) error {
	if got.err != nil || got.code == 0 {
		return fmt.Errorf("init chose a layout over two hand written candidates (exit %d): %w", got.code, errors.Join(got.err, ErrAcceptance))
	}
	switch {
	case !strings.Contains(got.stderr, "internal/adapters/outbound"):
		return fmt.Errorf("the refusal does not name internal/adapters/outbound: %q: %w", got.stderr, ErrAcceptance)
	case !m7OutAlone.MatchString(got.stderr):
		return fmt.Errorf("the refusal does not name internal/adapters/out: %q: %w", got.stderr, ErrAcceptance)
	case !strings.Contains(got.stderr, "adapter_sql"):
		return fmt.Errorf("the refusal does not name the key adapter_sql: %q: %w", got.stderr, ErrAcceptance)
	}
	return nil
}

// m7LayoutCases are the rows of M7.13 row 7.
func m7LayoutCases() []m7Case {
	return []m7Case{
		{name: "detected-layout", run: (*m7Suite).m7DetectedLayoutCase},
		{name: "ambiguous-layout", run: (*m7Suite).m7AmbiguousLayoutCase},
	}
}

// m7DetectedLayoutCase: init over the hub tree writes the layout its hand
// written adapters use and the sqlc output beside them.
func (s *m7Suite) m7DetectedLayoutCase(ctx context.Context) error {
	dir, got, err := s.m7Adopted(ctx, "layout-detected", "go,db", m7HubTree(false))
	if err != nil {
		return err
	}
	if initErr := success(got); initErr != nil {
		return fmt.Errorf("init over the hub tree: %w", initErr)
	}
	policy, err := readFile(filepath.Join(dir, policyFile))
	if err != nil {
		return err
	}
	return m7JudgeLayout(policy)
}

// m7AmbiguousLayoutCase: hand written adapters under both out and outbound
// stop init with both named.
func (s *m7Suite) m7AmbiguousLayoutCase(ctx context.Context) error {
	_, got, err := s.m7Adopted(ctx, "layout-ambiguous", "go,db", m7HubTree(true))
	if err != nil {
		return err
	}
	return m7JudgeAmbiguous(got)
}
