const module = "example.test/m"

// sampleProfile covers a.go fully through two overlapping runs, b.go fully
// and leaves c.go out of the profile.
const sampleProfile = `mode: atomic
example.test/m/a/a.go:5.13,7.2 2 1
example.test/m/a/a.go:9.13,11.2 3 0
example.test/m/a/a.go:9.13,11.2 3 4
example.test/m/b/b.go:3.13,4.2 1 1
`

func TestParseProfileMergesDuplicateBlocks(t *testing.T) {
	t.Parallel()
	files, err := parseProfile(strings.NewReader(sampleProfile))
	if err != nil {
		t.Fatal(err)
	}
	if got := files["example.test/m/a/a.go"].totals(); got != (tally{stmts: 5, covered: 5}) {
		t.Fatalf("a.go = %+v, duplicate blocks must merge as covered", got)
	}
	if got := files["example.test/m/b/b.go"].totals(); got != (tally{stmts: 1, covered: 1}) {
		t.Fatalf("b.go = %+v", got)
	}
	for _, bad := range []string{"x.go:1.1,2.2 1", "x.go 1 1", "x.go:1.1,2.2 a 1", "x.go:1.1,2.2 1 b"} {
		if _, err := parseProfile(strings.NewReader("mode: set\n" + bad + "\n")); err == nil {
			t.Errorf("%q must fail", bad)
		}
	}
}

func TestEvaluateAppliesTheFloorsAndTheStatementMinimum(t *testing.T) {
	t.Parallel()
	// c.go is measured here, one statement that no run executed.
	files, err := parseProfile(strings.NewReader(sampleProfile + "example.test/m/c/c.go:3.13,4.2 1 0\n"))
	if err != nil {
		t.Fatal(err)
	}
	sources := []string{"example.test/m/a/a.go", "example.test/m/b/b.go", "example.test/m/c/c.go"}
	strict := evaluate(files, sources, floors{percent: 80, statements: 1})
	if len(strict.Failures) != 2 || !strings.Contains(strict.Failures[0], "package example.test/m/c 0.0%") ||
		!strings.Contains(strict.Failures[1], "file example.test/m/c/c.go 0.0%") {
		t.Fatalf("failures = %v", strict.Failures)
	}
	text := strict.String()
	if !strings.HasPrefix(text, "total     85.7%     6/7     all\n") || !strings.Contains(text, "FAIL file example.test/m/c/c.go") {
		t.Fatalf("report = %s", text)
	}
	lenient := evaluate(files, sources, floors{percent: 80, statements: 20})
	if len(lenient.Failures) != 0 {
		t.Fatalf("small scopes must not fail: %v", lenient.Failures)
	}
	low := evaluate(files, sources, floors{percent: 90, statements: 20})
	if len(low.Failures) != 1 || low.Failures[0] != "total all 85.7%" {
		t.Fatalf("total floor = %v", low.Failures)
	}
	if (tally{}).percent() != 0 || (tally{stmts: 4, covered: 1}).percent() != 25 || (&report{}).String() != "" {
		t.Fatal("percent or empty report is wrong")
	}
}

func TestEvaluateFailsASourceTheProfileLeavesOut(t *testing.T) {
	t.Parallel()
	files, err := parseProfile(strings.NewReader(sampleProfile))
	if err != nil {
		t.Fatal(err)
	}
	sources := []string{"example.test/m/a/a.go", "example.test/m/b/b.go", "example.test/m/c/c.go"}
	for _, minimum := range []int{1, 20} {
		rep := evaluate(files, sources, floors{percent: 80, statements: minimum})
		if len(rep.Failures) != 1 || rep.Failures[0] != "file example.test/m/c/c.go not in the profile" {
			t.Fatalf("minimum %d: failures = %v", minimum, rep.Failures)
		}
	}
	if measured := evaluate(files, sources[:2], floors{percent: 80, statements: 20}); len(measured.Failures) != 0 {
		t.Fatalf("small measured scopes must not fail: %v", measured.Failures)
	}
}

// writeFixture writes a file under root, creating its directory.
func writeFixture(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

// fixtureModule is a module with a covered package, a test-only file, a
// generated file, a file without statements, a file whose statements sit
// in a function literal and a vendored tree.
func fixtureModule(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeFixture(t, root, "go.mod", "module "+module+"\n\ngo 1.27\n")
	writeFixture(t, root, "a/a.go", "package a\n\nfunc A() int { return 1 }\n")
	writeFixture(t, root, "a/a_test.go", "package a\n")
	writeFixture(t, root, "a/gen.go", "// Code generated by x. DO NOT EDIT.\npackage a\n\nfunc G() int { return 1 }\n")
	writeFixture(t, root, "a/types.go", "package a\n\ntype T struct{}\n")
	writeFixture(t, root, "a/lit.go", "package a\n\nvar L = func() int { return 1 }\n")
	writeFixture(t, root, "vendor/v/v.go", "package v\n\nfunc V() int { return 1 }\n")
	writeFixture(t, root, "a/testdata/x.go", "package x\n\nfunc X() int { return 1 }\n")
	return root
}

func TestSourceFilesListsOnlyWhatNeedsCoverage(t *testing.T) {
	t.Parallel()
	root := fixtureModule(t)
	got, err := sourceFiles(root, module)
	if err != nil || strings.Join(got, " ") != module+"/a/a.go "+module+"/a/lit.go" {
		t.Fatalf("sources = %v, %v", got, err)
	}
	if _, err := modulePath(t.TempDir()); err == nil {
		t.Fatal("a missing go.mod must fail")
	}
	writeFixture(t, root, "broken/b.go", "package b\n\nfunc {\n")
	if _, err := sourceFiles(root, module); err == nil {
		t.Fatal("a file that does not parse must fail")
	}
}

func TestExecuteExitCodes(t *testing.T) {
	t.Parallel()
	root := fixtureModule(t)
	writeFixture(t, root, "coverage.out", "mode: atomic\n"+module+"/a/a.go:3.13,3.27 1 1\n"+
		module+"/a/lit.go:3.20,3.34 1 1\n"+module+"/a/gen.go:4.14,4.27 1 0\n")
	profile := filepath.Join(root, "coverage.out")
	cases := map[string]struct {
		args []string
		code int
	}{
		"met":          {[]string{"-profile", profile, "-root", root, "-min-statements", "1"}, exitMet},
		"missed":       {[]string{"-profile", profile, "-root", root, "-min", "101", "-min-statements", "1"}, exitMissed},
		"no profile":   {[]string{"-profile", filepath.Join(root, "none.out"), "-root", root}, exitFailure},
		"bad flag":     {[]string{"-nope"}, exitFailure},
		"no module":    {[]string{"-profile", profile, "-root", t.TempDir()}, exitFailure},
		"small scopes": {[]string{"-profile", profile, "-root", root, "-min", "101"}, exitMissed},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			var stdout, stderr bytes.Buffer
			if got := execute(tc.args, &stdout, &stderr); got != tc.code {
				t.Fatalf("exit = %d, want %d, stdout = %q, stderr = %q", got, tc.code, stdout.String(), stderr.String())
			}
			if strings.Contains(stdout.String(), "gen.go") {
				t.Fatalf("the generated file was held to the floors: %q", stdout.String())
			}
		})
	}
}

func TestExecuteFailsASourceTheProfileLeavesOut(t *testing.T) {
	t.Parallel()
	root := fixtureModule(t)
	writeFixture(t, root, "b/b.go", "package b\n\nfunc B() int {\n\tx := 0\n"+strings.Repeat("\tx++\n", 20)+"\treturn x\n}\n")
	writeFixture(t, root, "coverage.out", "mode: atomic\n"+module+"/a/a.go:3.13,3.27 1 1\n"+module+"/a/lit.go:3.20,3.34 1 1\n")
	var stdout, stderr bytes.Buffer
	code := execute([]string{"-profile", filepath.Join(root, "coverage.out"), "-root", root}, &stdout, &stderr)
	if code != exitMissed || !strings.Contains(stdout.String(), "FAIL file "+module+"/b/b.go not in the profile\n") {
		t.Fatalf("exit = %d, stdout = %q, stderr = %q", code, stdout.String(), stderr.String())
	}
}
