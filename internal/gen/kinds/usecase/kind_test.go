func TestNewUsecaseWritesItsPartsAndAsksForItsPorts(t *testing.T) {
	t.Parallel()
	out, err := usecase.Kind().New(t.Context(), input(t, gentest.Contracts()), readPlan("Ledger", "Clock"))
	if err != nil {
		t.Fatal(err)
	}
	want := entry("ReadPlan", "read_plan", "Ledger", "Clock")
	if !reflect.DeepEqual(out.Entry, want) {
		t.Errorf("entry = %+v, want %+v", out.Entry, want)
	}
	if !slices.Equal(paths(out.Regenerable), want.Regenerable) || !slices.Equal(paths(out.Owned), want.Owned) {
		t.Errorf("regenerable %v, owned %v", paths(out.Regenerable), paths(out.Owned))
	}
	needs := []genkind.Need{
		{Kind: genkind.KindPort, Request: genkind.Request{Name: genkind.Name{Area: "growth", Type: "Ledger"}, Usecase: "ReadPlan", Port: asked, Ports: []string{"Ledger", "Clock"}}},
		{Kind: genkind.KindPort, Request: genkind.Request{Name: genkind.Name{Area: "growth", Type: "Clock"}, Usecase: "ReadPlan", Port: asked, Ports: []string{"Ledger", "Clock"}}},
	}
	if !reflect.DeepEqual(out.Needs, needs) {
		t.Errorf("needs = %+v, want %+v", out.Needs, needs)
	}
	bindings := []genkind.Binding{{Kind: genkind.KindUsecase, Area: "growth", Import: genkind.Import{Path: module + "/internal/application/growth"}, Call: "growth.NewUseCases"}}
	if !reflect.DeepEqual(out.Bindings, bindings) {
		t.Errorf("bindings = %+v", out.Bindings)
	}
	assertLaws(t, out)
}

func TestTheRegenerablePartOfReadPlan(t *testing.T) {
	t.Parallel()
	out, err := usecase.Kind().New(t.Context(), input(t, gentest.Contracts()), readPlan("Ledger", "Clock"))
	if err != nil {
		t.Fatal(err)
	}
	one := content(t, out.Regenerable, area+"zz_generated_read_plan.go")
	assertHas(t, one,
		"// Code generated by golaw 0.3.0 kind=usecase@1; DO NOT EDIT.",
		`const actionReadPlan = "growth: read plan"`,
		"// ReadPlan is the use case growth.ReadPlan over the ports Ledger and Clock.",
		"type ReadPlan struct { deps Deps }",
		"func NewReadPlan(deps Deps) *ReadPlan { return &ReadPlan{deps: deps} }",
		"func (u *ReadPlan) ready() error { return gensupport.Ready(actionReadPlan, u.deps.Ledger, u.deps.Clock) }",
	)
	if got := importPaths(t, one); !slices.Equal(got, []string{module + "/internal/gensupport"}) {
		t.Errorf("use case file imports %v", got)
	}
	assertHas(t, content(t, out.Regenerable, area+"zz_generated_usecases.go"),
		"type Deps struct { Clock Clock Ledger Ledger }", //nolint:dupword // a Deps field takes the name of its port type
		"type UseCases struct { ReadPlan *ReadPlan }",
		"func NewUseCases(deps Deps) UseCases { return UseCases{ ReadPlan: NewReadPlan(deps), } }",
	)
	test := content(t, out.Regenerable, area+"zz_generated_usecases_test.go")
	assertHas(t, test,
		"package growth_test",
		"type fakes struct { Clock *clocktest.Fake Ledger *ledgertest.Fake }",
		"return fakes{ Clock: clocktest.NewFake(), Ledger: ledgertest.NewFake(), }",
		"func (f fakes) deps() growth.Deps { return growth.Deps{ Clock: f.Clock, Ledger: f.Ledger, } }",
		"func TestEveryUseCaseRefusesAPortNotWired(t *testing.T) {",
		`"ReadPlan": func(ctx context.Context) []any { var in growth.AccountID return porttest.Pack(uc.ReadPlan.Execute(ctx, in)) },`,
		"if err, ok := got[len(got)-1].(error); !ok || !errors.Is(err, gensupport.ErrPortMissing) {",
	)
	wantImports := []string{
		"context", "errors", "testing", module + "/internal/application/growth", module + "/internal/application/growth/clocktest",
		module + "/internal/application/growth/ledgertest", module + "/internal/gensupport", module + "/internal/gensupport/porttest",
	}
	if got := importPaths(t, test); !slices.Equal(got, wantImports) {
		t.Errorf("area test imports %v, want %v", got, wantImports)
	}
}

func TestTheOwnedPartOfReadPlanHoldsItsHoleAndItsRedTest(t *testing.T) {
	t.Parallel()
	out, err := usecase.Kind().New(t.Context(), input(t, gentest.Contracts()), readPlan("Ledger", "Clock"))
	if err != nil {
		t.Fatal(err)
	}
	code := content(t, out.Owned, area+"read_plan.go")
	assertHas(t, code,
		"func (u *ReadPlan) Execute(ctx context.Context, in AccountID) (Plan, error) {",
		"var out Plan if err := u.ready(); err != nil { return out, err }",
		"// golaw:hole growth.read-plan implement ReadPlan over u.deps.Ledger and u.deps.Clock; wrap every port error with gensupport.Prefix(actionReadPlan);",
		`return out, gensupport.Hole("growth.read-plan", ctx, in)`,
	)
	if strings.Contains(code, "type AccountID") || strings.Contains(code, "type Plan ") {
		t.Error("read_plan.go declares a type growth already declares")
	}
	if got := importPaths(t, code); !slices.Equal(got, []string{"context", module + "/internal/gensupport"}) {
		t.Errorf("read_plan.go imports %v", got)
	}
	assertHas(t, content(t, out.Owned, area+"read_plan_test.go"),
		"func TestReadPlan(t *testing.T) {",
		"var in growth.AccountID _, err := growth.NewReadPlan(newFakes().deps()).Execute(t.Context(), in)",
		"if errors.Is(err, gensupport.ErrNotImplemented) {",
		`t.Fatal("hole growth.read-plan is open: implement ReadPlan over u.deps.Ledger and u.deps.Clock;`,
	)
}

