package render_test

import (
	"bytes"
	"errors"
	"io/fs"
	"strings"
	"testing"
	"testing/fstest"

	"github.com/cristianargotti/golaw/internal/gen/genkind"
	"github.com/cristianargotti/golaw/internal/gen/render"
	"github.com/cristianargotti/golaw/internal/genheader"
)

const module = "example.com/slice"

// shout is a template whose imports are scattered, unsorted and written
// in two declarations, with spacing gofmt normalizes.
const shout = `package {{.Package}}
import "fmt"
import (
	"example.com/slice/internal/application/growth"
	"strings"
)
// Shout {{lowerFirst "Shouts"}} the {{kebab "ReadPlan"}} name.
func Shout(  p growth.Plan) string { return strings.ToUpper(fmt.Sprint(p)) + {{printf "%q" .Suffix}} }
`

const shoutRendered = `// Code generated by golaw 0.3.0 kind=adapter-sql@1; DO NOT EDIT.

package postgres

import (
	"context"
	"fmt"
	"strings"

	"github.com/acme/x"

	"example.com/slice/internal/application/growth"
	gs "example.com/slice/internal/gensupport"
)

// Shout shouts the read-plan name.
func Shout(p growth.Plan) string { return strings.ToUpper(fmt.Sprint(p)) + "!" }
`

func tree(text string) fstest.MapFS {
	return fstest.MapFS{"x.go.tmpl": {Data: []byte(text)}}
}

func TestGoWritesTheHeaderTheGroupedImportsAndFormats(t *testing.T) {
	t.Parallel()
	header := genheader.Header{Version: "0.3.0", Kind: "adapter-sql", Template: 1}
	extra := []genkind.Import{{Path: "context"}, {Name: "gs", Path: module + "/internal/gensupport"}, {Path: "github.com/acme/x"}, {Path: "fmt"}}
	data := map[string]string{"Package": "postgres", "Suffix": "!"}
	got, err := render.Go(tree(shout), "x.go.tmpl", data, header, extra, module)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != shoutRendered {
		t.Errorf("Go =\n%s\nwant\n%s", got, shoutRendered)
	}
	again, err := render.Go(tree(shout), "x.go.tmpl", data, header, extra, module)
	if err != nil || !bytes.Equal(again, got) {
		t.Errorf("a second rendering differs: %v", err)
	}
	plain, err := render.Go(tree("package p\n\nvar x = 1\n"), "x.go.tmpl", nil, genheader.Header{}, nil, module)
	if err != nil || string(plain) != "package p\n\nvar x = 1\n" {
		t.Errorf("no header, no import = %q, %v", plain, err)
	}
}

// The red rows: every way a rendering can go wrong is ErrTemplate naming
// the template, never a file written with a hole in it.
func TestGoRefusesWhatDoesNotRender(t *testing.T) {
	t.Parallel()
	tests := map[string]struct {
		text    string
		data    any
		imports []genkind.Import
		want    string
	}{
		"a missing key":                  {"package {{.Package}}\n", map[string]string{}, nil, "x.go.tmpl"},
		"an unresolved value":            {"package p\n\nvar s = \"{{.Name}}\"\n", map[string]any{"Name": nil}, nil, "unresolved"},
		"a template that does not parse": {"package {{.Package\n", nil, nil, "x.go.tmpl"},
		"output that is not Go":          {"package p\n\nfunc (\n", nil, nil, "format"},
		"one path under two names":       {"package p\n\nimport \"fmt\"\n\nvar _ = fmt.Sprint\n", nil, []genkind.Import{{Name: "f", Path: "fmt"}}, "fmt"},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			_, err := render.Go(tree(tc.text), "x.go.tmpl", tc.data, genheader.Header{}, tc.imports, module)
			if !errors.Is(err, render.ErrTemplate) || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("Go = %v, want ErrTemplate naming %q", err, tc.want)
			}
		})
	}
	if _, err := render.Go(tree("package p\n"), "absent.go.tmpl", nil, genheader.Header{}, nil, module); !errors.Is(err, render.ErrTemplate) {
		t.Errorf("an absent template = %v", err)
	}
}

func TestTemplatesRefusesAKindOrVersionNotEmbedded(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		kind    string
		version int
	}{{"absent-kind", 1}, {"Port", 1}, {"port", 0}, {"", 1}} {
		if _, err := render.Templates(tc.kind, tc.version); !errors.Is(err, render.ErrTemplate) {
			t.Errorf("Templates(%q, %d) = %v, want ErrTemplate", tc.kind, tc.version, err)
		}
	}
	if _, err := render.Templates("absent-kind", 1); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("an absent tree = %v, want fs.ErrNotExist underneath", err)
	}
}
