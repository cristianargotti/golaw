func TestGeneratedWriteDeniesOnClaudeAndCodexWithTheSameReason(t *testing.T) {
	t.Parallel()
	red := map[string]struct {
		agent   string
		adapter hook.Adapter
		payload []byte
	}{
		"claude write":      {"claude", claudeAdapter(), written(t, "PreToolUse", genFake, "package ledgertest\n")},
		"claude edit":       {"claude", claudeAdapter(), genEdit(t, genFake, "package ledgertest", "package ledgertest // edited")},
		"codex update file": {"codex", codexAdapter(), genPatch(t, "*** Update File: "+genFake+"\n@@\n-// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\n \n package ledgertest\n")},
		"codex delete file": {"codex", codexAdapter(), genPatch(t, "*** Delete File: "+genFake+"\n")},
	}
	for name, tc := range red {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			result := before(t, tc.agent, tc.adapter, tc.payload, genBase(t))
			if result.Outcome != hook.Deny || result.CannotJudge || result.Reason != genReason || result.Human != genHuman {
				t.Fatalf("result = %+v\nwant the reason %q", result, genReason)
			}
		})
	}
}

func TestGeneratedWriteAllowsTheNearMissesOnClaudeAndCodex(t *testing.T) {
	t.Parallel()
	near := map[string]struct {
		agent   string
		adapter hook.Adapter
		payload []byte
	}{
		"claude write over a file that quotes the header": {"claude", claudeAdapter(), written(t, "PreToolUse", "notes.go", "package growth\n")},
		"codex update of the owned file of the entry":     {"codex", codexAdapter(), genPatch(t, "*** Update File: "+genCases+"\n@@\n package ledgertest\n+\n+const version = 1\n")},
	}
	for name, tc := range near {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			if result := before(t, tc.agent, tc.adapter, tc.payload, genBase(t)); result.Outcome != hook.Allow || strings.Contains(result.Reason, "generated") {
				t.Fatalf("result = %+v, want an allow", result)
			}
		})
	}
}

func TestManifestWriteDeniesOnClaudeAndCodex(t *testing.T) {
	t.Parallel()
	reason := ".golaw/gen.yml is written only by the golaw CLI: run golaw new <kind> <name> or golaw gen."
	human := "A operação foi bloqueada pela verificação gen.manifest-write no caminho .golaw/gen.yml. O manifesto é escrito só pelo golaw; rode golaw new ou golaw gen."
	for name, tc := range map[string]struct {
		agent   string
		adapter hook.Adapter
		payload []byte
	}{
		"claude write":      {"claude", claudeAdapter(), written(t, "PreToolUse", ".golaw/gen.yml", "golaw-gen: 1\n")},
		"codex delete file": {"codex", codexAdapter(), genPatch(t, "*** Delete File: .golaw/gen.yml\n")},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			result := before(t, tc.agent, tc.adapter, tc.payload, genBase(t))
			if result.Outcome != hook.Deny || result.Reason != reason || result.Human != human {
				t.Fatalf("result = %+v", result)
			}
		})
	}
	if near := before(t, "claude", claudeAdapter(), written(t, "PreToolUse", "docs/gen.yml", "golaw-gen: 1\n"), genBase(t)); near.Outcome != hook.Allow {
		t.Fatalf("near = %+v", near)
	}
}

func TestHandwrittenReasonDeniesABareMarkerOnClaude(t *testing.T) {
	t.Parallel()
	const stream = "internal/adapters/out/vendor/stream.go"
	red := before(t, "claude", claudeAdapter(), written(t, "PreToolUse", stream, "// golaw:handwritten\npackage vendor\n"), nil)
	reason := stream + ":1 adds golaw:handwritten without a reason: write why after the marker, for example // golaw:handwritten the vendor API streams a chunked body."
	human := "A operação foi bloqueada pela verificação gen.handwritten-reason no caminho " + stream + ". Escreva o motivo depois do marcador golaw:handwritten."
	if red.Outcome != hook.Deny || red.Reason != reason || red.Human != human {
		t.Fatalf("red = %+v", red)
	}
	near := before(t, "claude", claudeAdapter(), written(t, "PreToolUse", stream, "// golaw:handwritten the vendor API streams a chunked body\npackage vendor\n"), nil)
	if near.Outcome != hook.Allow {
		t.Fatalf("near = %+v", near)
	}
}

// genBash is the payload of a shell tool of the agent before it runs.
func genBash(t *testing.T, agent, command string) []byte {
	t.Helper()
	payload := map[string]any{
		"session_id": "session", "tool_use_id": "tool", "cwd": hooktest.Root,
		"hook_event_name": "PreToolUse", "tool_name": "Bash", "tool_input": map[string]any{"command": command},
	}
	if agent == "claude" {
		payload["agent_id"] = "agent"
	} else {
		payload["turn_id"], payload["transcript_path"], payload["model"], payload["permission_mode"] = "turn", nil, "model", "default"
	}
	data, err := json.Marshal(payload)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func TestALiteralShellTargetIsDeniedOnClaudeAndCodex(t *testing.T) {
	t.Parallel()
	for agent, adapter := range map[string]hook.Adapter{"claude": claudeAdapter(), "codex": codexAdapter()} {
		red := before(t, agent, adapter, genBash(t, agent, "echo x > "+hooktest.Root+"/"+genFake), genBase(t))
		if red.Outcome != hook.Deny || red.Reason != genReason {
			t.Errorf("%s red = %+v", agent, red)
		}
		near := before(t, agent, adapter, genBash(t, agent, "echo x > \"$OUT\""), genBase(t))
		if near.Outcome != hook.Allow {
			t.Errorf("%s near = %+v", agent, near)
		}
	}
}
