const (
	genPorts  = "internal/application/growth/ports.go"
	genFake   = "internal/application/growth/ledgertest/zz_generated_fake.go"
	genCases  = "internal/application/growth/ledgertest/cases.go"
	genHeader = "// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\n\npackage ledgertest\n"
	genReason = genFake + " is generated by golaw from " + genPorts + " (port Ledger): edit the contract and the hook regenerates it, or run golaw gen."
	genHuman  = "A operação foi bloqueada pela verificação gen.generated-write no caminho " + genFake + ". Edite o contrato " + genPorts + "; o golaw regenera este arquivo."
)

// genBase is a repository with the port entry of the growth fixture: its
// contract, its regenerable fake and its owned cases.
func genBase(t *testing.T) map[string]string {
	t.Helper()
	m := manifest.Manifest{Schema: manifest.Schema, Support: manifest.Support{Path: "internal/gensupport", Template: "support@1"}, Entries: []manifest.Entry{{
		Kind: genkind.KindPort, Template: "port@1", Name: "growth.Ledger",
		Contracts:   []manifest.Contract{{Path: genPorts, Symbol: "Ledger"}},
		Regenerable: []string{genFake}, Owned: []string{genCases},
	}}}
	data, err := m.Encode()
	if err != nil {
		t.Fatal(err)
	}
	return map[string]string{manifest.Path: string(data), genFake: genHeader, genCases: "package ledgertest\n", "notes.go": "package growth\n\nconst header = `\n" + genHeader + "`\n"}
}

