package report_test

import (
	"testing"

	"github.com/cristianargotti/golaw/internal/engine"
	"github.com/cristianargotti/golaw/internal/model"
	"github.com/cristianargotti/golaw/internal/report"
)

func genFinding(code, message string) model.Finding {
	return model.Finding{Check: "gen.generated-write", Path: "internal/a.go", Code: code, Message: message, Severity: model.SeverityDeny}
}

func TestGenFixNamesTheContractToEdit(t *testing.T) {
	t.Parallel()
	tests := map[string]struct {
		language string
		finding  model.Finding
		want     string
		ok       bool
	}{
		"red: a golaw contract":                     {report.Portuguese, genFinding("generated-write", "is generated by golaw from internal/application/growth/ports.go (port Ledger): edit the contract and the hook regenerates it, or run golaw gen."), "Edite o contrato internal/application/growth/ports.go; o golaw regenera este arquivo.", true},
		"red: a golaw file without a contract file": {report.Portuguese, genFinding("generated-write", "is generated by golaw (port@1): run golaw gen."), "Rode golaw gen; o golaw regenera este arquivo.", true},
		"red: a manifest entry":                     {report.Portuguese, genFinding("generated-write", "is generated by golaw from the manifest entry usecase growth.ReadPlan: rerun golaw new usecase growth.ReadPlan with its flags, or run golaw gen."), "Rode golaw gen; o golaw regenera este arquivo.", true},
		"red: an sqlc query":                        {report.Portuguese, genFinding("generated-write", "is generated by sqlc from db/queries/plans.sql: edit the query and run golaw gen."), "Edite a consulta db/queries/plans.sql e rode golaw gen.", true},
		"red: the sqlc schema":                      {report.Portuguese, genFinding("generated-write", "is generated by sqlc from the schema and queries sqlc.yaml names: edit them and run golaw gen."), "Edite o esquema e as consultas que o sqlc.yaml nomeia e rode golaw gen.", true},
		"red: the OpenAPI document":                 {report.Portuguese, genFinding("generated-write", "is generated by oapi-codegen from api/openapi.yaml: edit the document and run golaw gen."), "Edite o documento api/openapi.yaml e rode golaw gen.", true},
		"near: another code":                        {report.Portuguese, genFinding("file-length", "has 312 lines"), "", false},
		"near: another language":                    {"en", genFinding("generated-write", "is generated by golaw (port@1): run golaw gen."), "", false},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			got, ok := report.GenFix(tc.language, tc.finding)
			if got != tc.want || ok != tc.ok {
				t.Errorf("GenFix = %q, %v, want %q, %v", got, ok, tc.want, tc.ok)
			}
		})
	}
}

func TestHumanRendersTheGenPhrase(t *testing.T) {
	t.Parallel()
	decision := engine.Decision{Mode: model.ModeHook, Verdict: engine.VerdictDeny, Findings: []model.Finding{genFinding("generated-write", "english")}}
	want := "golaw bloqueou a operação: arquivo gerado editado por um agente; edite o contrato do arquivo e rode golaw gen (verificação gen.generated-write, arquivo internal/a.go)."
	if got := report.Human(report.Portuguese, decision); got != want {
		t.Errorf("Human = %q\nwant %q", got, want)
	}
}
