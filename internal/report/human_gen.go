package report

import (
	"strings"

	"github.com/cristianargotti/golaw/internal/model"
)

// The prefixes of the gen.generated-write messages, repeated from
// internal/checks/genguard because report imports no check package; the
// person's sentence names the same contract the agent's reason does.
const (
	genCode        = "generated-write"
	genGolawFrom   = "is generated by golaw from "
	genGolawRef    = "is generated by golaw ("
	genSQLCFrom    = "is generated by sqlc from "
	genOAPIFrom    = "is generated by oapi-codegen from "
	genEntry       = "the manifest entry "
	genSchema      = "the schema"
	genRunGen      = "Rode golaw gen; o golaw regenera este arquivo."
	genSchemaFix   = "Edite o esquema e as consultas que o sqlc.yaml nomeia e rode golaw gen."
	genReasonBreak = ": "
)

// genPhrases are the sentences of the gen family.
func genPhrases() []sentence {
	return []sentence{
		{code: genCode, text: "arquivo gerado editado por um agente; edite o contrato do arquivo e rode golaw gen"},
		{code: "manifest-write", text: "manifesto de geração editado por um agente; o manifesto é escrito só pelo golaw; rode golaw new ou golaw gen"},
		{code: "handwritten-reason", text: "marcador golaw:handwritten sem motivo; escreva o motivo depois do marcador golaw:handwritten"},
		{code: "handwritten", text: "arquivo marcado como escrito à mão; o golaw não gera código para ele"},
	}
}

// GenFix is the person's remedy for a gen.generated-write finding: the
// contract its message names, read from the message's own grammar, so the
// person edits the same file the agent is told to. Any other code or
// language answers false and keeps the shared remedy of Fix.
func GenFix(language string, f model.Finding) (string, bool) {
	if language != Portuguese || f.Code != genCode {
		return "", false
	}
	message := f.Message
	if rest, ok := strings.CutPrefix(message, genGolawFrom); ok {
		if strings.HasPrefix(rest, genEntry) {
			return genRunGen, true
		}
		contract, _, _ := strings.Cut(rest, genReasonBreak)
		contract, _, _ = strings.Cut(contract, " (")
		return "Edite o contrato " + contract + "; o golaw regenera este arquivo.", true
	}
	if strings.HasPrefix(message, genGolawRef) {
		return genRunGen, true
	}
	if rest, ok := strings.CutPrefix(message, genSQLCFrom); ok {
		if strings.HasPrefix(rest, genSchema) {
			return genSchemaFix, true
		}
		query, _, _ := strings.Cut(rest, genReasonBreak)
		return "Edite a consulta " + query + " e rode golaw gen.", true
	}
	if rest, ok := strings.CutPrefix(message, genOAPIFrom); ok {
		document, _, _ := strings.Cut(rest, genReasonBreak)
		return "Edite o documento " + document + " e rode golaw gen.", true
	}
	return "", false
}
