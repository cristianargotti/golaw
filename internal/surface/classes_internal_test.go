package surface

import (
	"strings"
	"testing"
)

func TestClassOfJudgesTheNameThenTheContent(t *testing.T) {
	t.Parallel()
	wide := strings.Repeat("a", 250)
	tests := map[string]struct {
		path     string
		language Language
		content  string
		want     Class
	}{
		"hand written source":                       {path: "views/panel.js", language: JavaScript, content: "function a() {}\n", want: ClassSource},
		"a .min. name":                              {path: "views/app.min.js", language: JavaScript, content: "a()\n", want: ClassMinified},
		"a .min. style sheet":                       {path: "views/site.min.css", language: CSS, want: ClassMinified},
		"one long line of script":                   {path: "views/bundle.js", language: JavaScript, content: wide, want: ClassMinified},
		"one long line of style":                    {path: "views/charts.css", language: CSS, content: wide + "\n", want: ClassMinified},
		"wide lines under the average (near)":       {path: "views/wide.js", language: JavaScript, content: strings.Repeat(strings.Repeat("b", 150)+"\n", 3), want: ClassSource},
		"a one line template keeps its class":       {path: "infra/stack.json", language: CloudFormation, content: wide, want: ClassSource},
		"an empty script (near)":                    {path: "views/empty.js", language: JavaScript, want: ClassSource},
		"a gen directory":                           {path: "internal/gen/client.ts", language: TypeScript, want: ClassGenerated},
		"a sqlcgen directory":                       {path: "internal/store/sqlcgen/q.ts", language: TypeScript, want: ClassGenerated},
		"test/mocks at the root":                    {path: "test/mocks/api.js", language: JavaScript, want: ClassGenerated},
		"a generator directory (near)":              {path: "generator/build.js", language: JavaScript, want: ClassSource},
		"mocks below the root (near)":               {path: "web/test/mocks/api.js", language: JavaScript, want: ClassSource},
		"a file named gen (near)":                   {path: "scripts/gen", language: Shell, content: "#!/bin/sh\n", want: ClassSource},
		"a shell header":                            {path: "scripts/gen.sh", language: Shell, content: "#!/bin/sh\n# Code generated by stub. DO NOT EDIT.\n", want: ClassGenerated},
		"a Python header":                           {path: "deploy/pb.py", language: Python, content: "# Code generated by protoc. DO NOT EDIT.\n", want: ClassGenerated},
		"an HTML header":                            {path: "views/out.html", language: HTML, content: "<!-- Code generated by tmpl. DO NOT EDIT. -->\n", want: ClassGenerated},
		"a script header":                           {path: "views/api.ts", language: TypeScript, content: "// Code generated by openapi. DO NOT EDIT.\n", want: ClassGenerated},
		"a style header":                            {path: "views/out.css", language: CSS, content: "/* Code generated by sass. DO NOT EDIT. */\n", want: ClassGenerated},
		"the header quoted in a string (near)":      {path: "views/doc.js", language: JavaScript, content: "const s = \"// Code generated by x. DO NOT EDIT.\";\n", want: ClassSource},
		"a testdata segment":                        {path: "internal/panel/testdata/growth.jsx", language: JSX, want: ClassFixture},
		"testdata at the root":                      {path: "testdata/a.py", language: Python, want: ClassFixture},
		"a directory named like testdata (near)":    {path: "testdatabase/a.py", language: Python, want: ClassSource},
		"a generated fixture is generated":          {path: "testdata/gen/a.js", language: JavaScript, want: ClassGenerated},
		"a declaration file":                        {path: "web/types.d.ts", language: TypeScript, content: "export type A = string;\n", want: ClassDeclaration},
		"a minified declaration is minified":        {path: "web/types.min.d.ts", language: TypeScript, want: ClassMinified},
		"a TypeScript source next to it (near)":     {path: "web/types.ts", language: TypeScript, content: "export type A = string;\n", want: ClassSource},
		"a declaration of another extension (near)": {path: "web/types.d.mts", language: TypeScript, want: ClassSource},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			if got := classOf(tc.path, tc.language, []byte(tc.content)); got != tc.want {
				t.Fatalf("classOf(%q) = %s, want %s", tc.path, got, tc.want)
			}
		})
	}
}

func TestClassNamesItself(t *testing.T) {
	t.Parallel()
	names := map[Class]string{
		ClassSource: "source", ClassMinified: "minified", ClassGenerated: "generated",
		ClassFixture: "fixture", ClassDeclaration: "declaration", Class(0): "Class(0)",
	}
	for class, want := range names {
		if got := class.String(); got != want {
			t.Errorf("Class(%d).String() = %q, want %q", int(class), got, want)
		}
	}
}
