package proof_test

import (
	"testing"

	"github.com/cristianargotti/golaw/internal/model"
	"github.com/cristianargotti/golaw/internal/proof"
)

func TestClassifyAgreesWithTheWorktreeOnGeneratedHeaders(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, content string
		want          model.FileClass
	}{
		{"red swaggo header", "// Package api Code generated by swaggo/swag. DO NOT EDIT\npackage api\n", model.ClassGenerated},
		{"red convention", "// Code generated by mockery. DO NOT EDIT.\npackage mocks\n", model.ClassGenerated},
		{"near prose", "// Package api wraps code generated by swaggo; do not edit the generated files.\npackage api\n", model.ClassTracked},
	} {
		if got := proof.Classify("api/docs.go", []byte(tc.content)); got != tc.want {
			t.Fatalf("%s: class = %v, want %v", tc.name, got, tc.want)
		}
	}
}
