package proof_test

import (
	"errors"
	"strings"
	"testing"

	"github.com/cristianargotti/golaw/internal/model"
	"github.com/cristianargotti/golaw/internal/proof"
)

func TestTree(t *testing.T) {
	t.Parallel()
	source := map[string][]byte{"b.go": []byte("package b\n"), "a_test.go": []byte("package a\n")}
	tree := proof.NewTree(source)
	source["b.go"][0] = 'X'
	files := tree.Files()
	if len(files) != 2 || files[0].Path != "a_test.go" || files[0].Class != model.ClassTest || files[1].Size != 10 {
		t.Errorf("Files() = %+v", files)
	}
	data, err := tree.Read("b.go")
	if err != nil || string(data) != "package b\n" {
		t.Errorf("Read must copy at construction: %q, %v", data, err)
	}
	data[0] = 'Y'
	if again, err := tree.Read("b.go"); err != nil || again[0] != 'p' {
		t.Error("Read must return a copy")
	}
	if _, err := tree.Read("c.go"); !errors.Is(err, model.ErrNotInSnapshot) {
		t.Errorf("unknown path: %v", err)
	}
	if tree.Class("c.go") != model.ClassUnknown || tree.Class("b.go") != model.ClassTracked {
		t.Error("Class is wrong")
	}
	big := proof.NewTree(map[string][]byte{"big.bin": make([]byte, model.MaxReadBytes+1)})
	if _, err := big.Read("big.bin"); !errors.Is(err, model.ErrTooLarge) {
		t.Errorf("oversized read: %v", err)
	}
}

func TestClassify(t *testing.T) {
	t.Parallel()
	cases := []struct {
		path    string
		content string
		want    model.FileClass
	}{
		{"a.png", "x\x00y", model.ClassBinary},
		{"gen_test.go", "// Code generated by x. DO NOT EDIT.\npackage p\n", model.ClassGenerated},
		{"testdata/x.go", "package x\n", model.ClassFixture},
		{"internal/a/testdata/x_test.go", "package x\n", model.ClassFixture},
		{"a_test.go", "package a\n", model.ClassTest},
		{"a.go", "package a\n", model.ClassTracked},
		{"big.bin", strings.Repeat("a", 8000) + "\x00", model.ClassTracked},
	}
	for _, c := range cases {
		if got := proof.Classify(c.path, []byte(c.content)); got != c.want {
			t.Errorf("Classify(%s) = %s, want %s", c.path, got, c.want)
		}
	}
}
