func writeCoverageFile(t *testing.T, root, name, content string) {
	t.Helper()
	target := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(target), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func coverageRoot(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeCoverageFile(t, root, "go.mod", "module "+moduleName+"\n\ngo 1.27\n")
	writeCoverageFile(t, root, "value.go", valueSource)
	return root
}

func TestEvaluateFloorsAndDuplicates(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name    string
		profile string
		covered int
		fail    int
	}{
		{
			"red-below-eighty",
			"mode: atomic\n" +
				moduleName + "/value.go:4.2,18.5 15 1\n" +
				moduleName + "/value.go:19.2,23.10 5 0\n",
			15, 3,
		},
		{
			"near-exactly-eighty",
			"mode: atomic\n" +
				moduleName + "/value.go:4.2,19.5 16 1\n" +
				moduleName + "/value.go:20.2,23.10 4 0\n",
			16, 0,
		},
		{
			"near-covered-by-either-run",
			"mode: count\n" +
				moduleName + "/value.go:4.2,23.10 20 0\n" +
				moduleName + "/value.go:4.2,23.10 20 7\n",
			20, 0,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			report, err := coverage.Evaluate(
				strings.NewReader(tc.profile), coverageRoot(t),
				coverage.DefaultFloors(),
			)
			want := coverage.Measure{
				Name: "total", Statements: 20, Covered: tc.covered,
			}
			if err != nil || report.Total != want ||
				len(report.Failures) != tc.fail {
				t.Fatalf("report = %+v, error = %v", report, err)
			}
			if len(report.Files) != 1 || report.Files[0].Name != "value.go" ||
				len(report.Packages) != 1 || report.Packages[0].Name != moduleName {
				t.Fatalf("units = %+v", report)
			}
		})
	}
}

func TestEvaluateRequiresBuiltSources(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name   string
		path   string
		source string
		fail   bool
	}{
		{"red-absent-source", "other.go", "package sample\nfunc Other() int { return 1 }\n", true},
		{"near-test", "other_test.go", "package sample\nfunc Other() int { return 1 }\n", false},
		{"near-declarations", "other.go", "package sample\ntype Other struct{}\n", false},
		{"near-generated", "other.go", "// Code generated by fixture. DO NOT EDIT.\npackage sample\nfunc Other() int { return 1 }\n", false},
		{"near-excluded-build", "other.go", "//go:build ignore\n\npackage sample\nfunc Other() int { return 1 }\n", false},
		{"near-fixture", "testdata/other.go", "package sample\nfunc Other() int { return 1 }\n", false},
		{"red-function-literal", "other.go", "package sample\nvar Other = func() int { return 1 }\n", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := coverageRoot(t)
			writeCoverageFile(t, root, tc.path, tc.source)
			profile := "mode: atomic\n" +
				moduleName + "/value.go:4.2,23.10 20 1\n" +
				"example.test/foreign/foreign.go:1.1,2.1 100 0\n"
			report, err := coverage.Evaluate(
				strings.NewReader(profile), root, coverage.DefaultFloors(),
			)
			if err != nil || (len(report.Failures) != 0) != tc.fail {
				t.Fatalf("report = %+v, error = %v", report, err)
			}
			if report.Total.Statements != 20 || report.Total.Covered != 20 {
				t.Fatalf("invented statement count: %+v", report.Total)
			}
			if tc.fail && (len(report.Failures) != 1 ||
				report.Failures[0].Name != tc.path ||
				report.Failures[0].Statements != 0) {
				t.Fatalf("missing source = %+v", report.Failures)
			}
		})
	}
}

func TestEvaluateRejectsBrokenBlocks(t *testing.T) {
	t.Parallel()
	for _, body := range []string{
		"value.go:1.1,2.1 1\n",
		"value.go 1 1\n",
		"value.go:1.1,2.1 x 1\n",
		"value.go:1.1,2.1 1 x\n",
		"value.go:1.1,2.1 -1 1\n",
		"value.go:1.1,2.1 1 -1\n",
		"value.go:1.1,2.1 1 0\nvalue.go:1.1,2.1 2 1\n",
	} {
		t.Run(body, func(t *testing.T) {
			t.Parallel()
			_, err := coverage.Evaluate(
				strings.NewReader("mode: atomic\n"+body),
				coverageRoot(t), coverage.DefaultFloors(),
			)
			if !errors.Is(err, coverage.ErrProfile) {
				t.Fatalf("error = %v", err)
			}
		})
	}
}

func TestCoverageDefaultsAndModuleFailure(t *testing.T) {
	t.Parallel()
	want := coverage.Floors{
		Total: 80, Package: 80, File: 80, MinStatements: 20,
	}
	if got := coverage.DefaultFloors(); !reflect.DeepEqual(got, want) {
		t.Fatalf("defaults = %+v", got)
	}
	if (coverage.Measure{}).Percent() != 100 {
		t.Fatal("empty measured unit is not fully covered")
	}
	root := t.TempDir()
	writeCoverageFile(t, root, "go.mod", "go 1.27\n")
	_, err := coverage.Evaluate(strings.NewReader("mode: atomic\n"), root, want)
	if !errors.Is(err, coverage.ErrModule) {
		t.Fatalf("error = %v", err)
	}
}
