package coverage_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/cristianargotti/golaw/internal/coverage"
)

const otherSource = "package sample\n\nfunc Other() int { return 1 }\n"

func TestEvaluateHoldsGolawGeneratedFilesToTheFloors(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name   string
		path   string
		source string
		fail   bool
	}{
		{"red-a-golaw-regenerable-file-is-measured", "zz_generated_other.go", "// Code generated by golaw 0.3.0 kind=adapter-sql@1; DO NOT EDIT.\n\n" + otherSource, true},
		{"red-a-golaw-file-of-another-kind-is-measured", "zz_generated_fake.go", "// Code generated by golaw 1.0.0 kind=port@2; DO NOT EDIT.\n\n" + otherSource, true},
		{"near-a-third-party-header-stays-out", "plans.sql.go", "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.31.1\n\n" + otherSource, false},
		{"near-a-golaw-header-below-the-first-line-stays-out", "other.go", "// Package sample holds values.\n// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\n" + otherSource, false},
		{"near-a-golaw-test-file-is-never-a-source", "zz_generated_other_test.go", "// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\n\n" + otherSource, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := coverageRoot(t)
			writeCoverageFile(t, root, tc.path, tc.source)
			profile := "mode: atomic\n" + moduleName + "/value.go:4.2,23.10 20 1\n"
			report, err := coverage.Evaluate(strings.NewReader(profile), root, coverage.DefaultFloors())
			if err != nil {
				t.Fatal(err)
			}
			// A source the profile omits is a failure (the existing
			// red-absent-source row), so it may sit in any of the lists.
			measured := false
			for _, file := range slices.Concat(report.Files, report.Failures, report.Skipped) {
				measured = measured || file.Name == tc.path
			}
			if measured != tc.fail || (len(report.Failures) != 0) != tc.fail {
				t.Fatalf("report = %+v, want %s measured and failing: %v", report, tc.path, tc.fail)
			}
		})
	}
}
