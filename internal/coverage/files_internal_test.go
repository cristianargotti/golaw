func writeSourceFile(t *testing.T, root, name, data string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestSourceFilesStayInTheActiveModule(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	const source = "package sample\nfunc Value() int { return 1 }\n"
	for name, content := range map[string]string{
		"go.mod":                  "module example.test/sample\n",
		"value.go":                source,
		"nested/go.mod":           "module example.test/nested\n",
		"nested/other.go":         source,
		"nested/deeper/deep.go":   source,
		".hidden/other.go":        source,
		"_private/other.go":       source,
		"vendor/other.go":         source,
		"node_modules/other.go":   source,
		"testdata/other.go":       source,
		"dist/other.go":           source,
		".git/other.go":           source,
		"active/active.go":        "//go:build " + build.Default.GOOS + "\n\n" + source,
		"inactive/inactive.go":    "//go:build !" + build.Default.GOOS + "\n\n" + source,
		"active/external_test.go": source,
	} {
		writeSourceFile(t, root, name, content)
	}
	got, err := sourceFiles(root, "example.test/sample")
	want := []string{"example.test/sample/active/active.go", "example.test/sample/value.go"}
	if err != nil || !reflect.DeepEqual(got, want) {
		t.Fatalf("sources = %v, error = %v", got, err)
	}
}

func TestSourceDirectoryNamedGoModIsNotAModule(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeSourceFile(t, root, "go.mod", "module example.test/sample\n")
	writeSourceFile(t, root, "nested/go.mod/notes.txt", "module notes\n")
	writeSourceFile(t, root, "nested/value.go", "package nested\nfunc Value() int { return 1 }\n")
	got, err := sourceFiles(root, "example.test/sample")
	want := []string{"example.test/sample/nested/value.go"}
	if err != nil || !reflect.DeepEqual(got, want) {
		t.Fatalf("sources = %v, error = %v", got, err)
	}
}

func TestSourceFailuresPreserveTheCause(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	missing := filepath.Join(root, "missing")
	if _, err := modulePath(missing); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("module error = %v", err)
	}
	if _, err := sourceFiles(missing, "example.test/sample"); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("walk error = %v", err)
	}
	if _, err := needsCoverage(missing); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("source error = %v", err)
	}
	writeSourceFile(t, root, "broken.go", "//go:build (\n\npackage broken\n")
	if _, _, err := sourceName(root, "example.test/sample", filepath.Join(root, "broken.go")); err == nil {
		t.Fatal("malformed build constraint answered clean")
	}
}

func TestSourcesRequireExecutableStatements(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name   string
		source string
		want   bool
	}{
		{"declarations", "package sample\ntype Value int\n", false},
		{"declaration-only-function", "package sample\nfunc Value()\n", false},
		{"empty-function", "package sample\nfunc Value() {}\n", false},
		{"empty-literal", "package sample\nvar Value = func() {}\n", false},
		{"function", "package sample\nfunc Value() { println(1) }\n", true},
		{"literal", "package sample\nvar Value = func() { println(1) }\n", true},
		{"generated", "// Code generated by fixture. DO NOT EDIT.\npackage sample\nfunc Value() { println(1) }\n", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			writeSourceFile(t, root, "value.go", tc.source)
			got, err := needsCoverage(filepath.Join(root, "value.go"))
			if err != nil || got != tc.want {
				t.Fatalf("needs coverage = %t, error = %v", got, err)
			}
		})
	}
}

func TestSourceModuleBoundaryReadFailure(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	boundary := filepath.Join(root, "nested")
	if err := os.Mkdir(boundary, 0o700); err != nil {
		t.Fatal(err)
	}
	moduleFile := filepath.Join(boundary, "go.mod")
	if err := os.Symlink("go.mod", moduleFile); err != nil {
		t.Skipf("symlink unavailable: %v", err)
	}
	_, err := sourceFiles(root, "example.test/sample")
	var pathError *os.PathError
	if !errors.As(err, &pathError) || pathError.Path != moduleFile {
		t.Fatalf("module boundary error = %v", err)
	}
}

func TestModuleDirectiveSyntax(t *testing.T) {
	t.Parallel()
	for _, directive := range []string{
		"module example.test/sample\n",
		"module\texample.test/sample\n",
		"module example.test/sample // module comment\n",
		"module \"example.test/sample\"\n",
		"module \"example.test/sample\" // module comment\n",
		"module example.test/sample// module comment\n",
		"module \"example.test/sample\"// module comment\n",
	} {
		t.Run(directive, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			writeSourceFile(t, root, "go.mod", directive+"\ngo 1.27\n")
			got, err := modulePath(root)
			if err != nil || got != "example.test/sample" {
				t.Fatalf("module = %q, error = %v", got, err)
			}
		})
	}
}

func TestModuleDirectiveWithoutAValue(t *testing.T) {
	t.Parallel()
	for _, directive := range []string{
		"go 1.27\n",
		"module\n",
		"module \n",
		"module // module comment\n",
		"module \"\"\n",
		"module \"example.test/sample\n",
		"module example.test/sample unexpected\n",
	} {
		t.Run(directive, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			writeSourceFile(t, root, "go.mod", directive)
			_, err := modulePath(root)
			if !errors.Is(err, ErrModule) {
				t.Fatalf("module error = %v", err)
			}
		})
	}
}
