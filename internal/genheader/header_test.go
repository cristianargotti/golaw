package genheader_test

import (
	"testing"

	"github.com/cristianargotti/golaw/internal/genheader"
)

func TestHeaderLineAndRefSpellTheAddendumForm(t *testing.T) {
	t.Parallel()
	h := genheader.Header{Version: "0.3.0", Kind: "adapter-sql", Template: 1}
	if got, want := h.Line(), "// Code generated by golaw 0.3.0 kind=adapter-sql@1; DO NOT EDIT."; got != want {
		t.Errorf("Line() = %q, want %q", got, want)
	}
	if got := h.Ref(); got != "adapter-sql@1" {
		t.Errorf("Ref() = %q, want adapter-sql@1", got)
	}
	if genheader.Tool != "golaw" || genheader.HandwrittenMarker != "golaw:handwritten" {
		t.Errorf("constants = %q, %q", genheader.Tool, genheader.HandwrittenMarker)
	}
}

func TestParseReadsTheFirstLineOnly(t *testing.T) {
	t.Parallel()
	tests := map[string]struct {
		content string
		want    genheader.Header
		ok      bool
	}{
		"red: a golaw header before the package clause": {
			content: "// Code generated by golaw 0.3.0 kind=adapter-sql@1; DO NOT EDIT.\n\npackage postgres\n",
			want:    genheader.Header{Version: "0.3.0", Kind: "adapter-sql", Template: 1}, ok: true,
		},
		"red: a prerelease version and a two digit template": {
			content: "// Code generated by golaw 0.3.0-rc.1+build.7 kind=port@12; DO NOT EDIT.\npackage growth\n",
			want:    genheader.Header{Version: "0.3.0-rc.1+build.7", Kind: "port", Template: 12}, ok: true,
		},
		"red: the line alone without a newline": {
			content: "// Code generated by golaw 0.3.0 kind=support@1; DO NOT EDIT.",
			want:    genheader.Header{Version: "0.3.0", Kind: "support", Template: 1}, ok: true,
		},
		"red: a carriage return before the newline": {
			content: "// Code generated by golaw 0.3.0 kind=usecase@1; DO NOT EDIT.\r\npackage growth\r\n",
			want:    genheader.Header{Version: "0.3.0", Kind: "usecase", Template: 1}, ok: true,
		},
		"near: a third party header":           {content: "// Code generated by sqlc. DO NOT EDIT.\npackage sqlcgen\n"},
		"near: the header on the second line":  {content: "// Package growth holds plans.\n// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\npackage growth\n"},
		"near: no final period":                {content: "// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT\n"},
		"near: template zero":                  {content: "// Code generated by golaw 0.3.0 kind=port@0; DO NOT EDIT.\n"},
		"near: template with a leading zero":   {content: "// Code generated by golaw 0.3.0 kind=port@01; DO NOT EDIT.\n"},
		"near: an upper case kind":             {content: "// Code generated by golaw 0.3.0 kind=Port@1; DO NOT EDIT.\n"},
		"near: a kind with a digit":            {content: "// Code generated by golaw 0.3.0 kind=port2@1; DO NOT EDIT.\n"},
		"near: a kind ending in a hyphen":      {content: "// Code generated by golaw 0.3.0 kind=port-@1; DO NOT EDIT.\n"},
		"near: no version":                     {content: "// Code generated by golaw  kind=port@1; DO NOT EDIT.\n"},
		"near: a version with a slash":         {content: "// Code generated by golaw 0.3/0 kind=port@1; DO NOT EDIT.\n"},
		"near: text after the period":          {content: "// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT. now\n"},
		"near: a header quoted in a body":      {content: "package growth\n\nconst h = \"// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\"\n"},
		"near: an empty file":                  {content: ""},
		"near: another generator named golaw2": {content: "// Code generated by golaw2 0.3.0 kind=port@1; DO NOT EDIT.\n"},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			got, ok := genheader.Parse([]byte(tc.content))
			if ok != tc.ok || got != tc.want {
				t.Errorf("Parse = %+v, %v; want %+v, %v", got, ok, tc.want, tc.ok)
			}
		})
	}
}

func TestLineParsesBackForEveryKind(t *testing.T) {
	t.Parallel()
	for _, kind := range []string{"port", "adapter-sql", "adapter-http", "usecase", "handler", "wiring", "support"} {
		h := genheader.Header{Version: "1.2.3", Kind: kind, Template: 3}
		got, ok := genheader.Parse([]byte(h.Line() + "\n\npackage x\n"))
		if !ok || got != h {
			t.Errorf("Parse(Line()) of %s = %+v, %v", kind, got, ok)
		}
	}
}
