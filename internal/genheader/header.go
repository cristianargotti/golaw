package genheader

import (
	"bytes"
	"strconv"
	"strings"
)

// Tool is the generator name the golaw header carries.
const Tool = "golaw"

// HandwrittenMarker is the escape of M7.9.5, written in a file's leading comments.
const HandwrittenMarker = "golaw:handwritten"

// The literal ends of the header; Parse cuts them instead of matching a
// regular expression, so a near form never passes through a loose pattern.
const (
	linePrefix = "// Code generated by " + Tool + " "
	lineSuffix = "; DO NOT EDIT."
	kindPrefix = "kind="
)

// Header is the first line of a golaw regenerable file (M7.4.1, A38), of
// the form "// Code generated by golaw <Version> kind=<Kind>@<Template>; DO
// NOT EDIT." with the version, the kind and the template version as fields.
type Header struct {
	Version  string // the kit version that last wrote the file; drift never compares it
	Kind     string // the kind that renders the file, "adapter-sql"
	Template int    // the template version of the kind
}

// Line is the exact header line, without the newline.
func (h Header) Line() string {
	return linePrefix + h.Version + " " + kindPrefix + h.Ref() + lineSuffix
}

// Ref is "<Kind>@<Template>", the template value the manifest records.
func (h Header) Ref() string {
	return h.Kind + "@" + strconv.Itoa(h.Template)
}

// Parse reads the golaw header from the first line of content alone, so a
// header quoted further down a body never turns a file into a golaw one.
func Parse(content []byte) (Header, bool) {
	first, _, _ := bytes.Cut(content, []byte("\n"))
	line := strings.TrimSuffix(string(first), "\r")
	middle, ok := strings.CutPrefix(line, linePrefix)
	if !ok {
		return Header{}, false
	}
	middle, ok = strings.CutSuffix(middle, lineSuffix)
	if !ok {
		return Header{}, false
	}
	version, ref, ok := strings.Cut(middle, " ")
	if !ok || !versionOK(version) {
		return Header{}, false
	}
	ref, ok = strings.CutPrefix(ref, kindPrefix)
	if !ok {
		return Header{}, false
	}
	kind, number, ok := strings.Cut(ref, "@")
	if !ok || !kindOK(kind) {
		return Header{}, false
	}
	template, ok := templateOK(number)
	if !ok {
		return Header{}, false
	}
	return Header{Version: version, Kind: kind, Template: template}, true
}

// versionOK admits a semantic version with its prerelease and build parts.
func versionOK(version string) bool {
	if version == "" {
		return false
	}
	for _, c := range []byte(version) {
		switch {
		case c >= '0' && c <= '9', c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z':
		case c == '.', c == '+', c == '-':
		default:
			return false
		}
	}
	return true
}

// kindOK admits lower case words joined by hyphens.
func kindOK(kind string) bool {
	if kind == "" || kind[0] == '-' || kind[len(kind)-1] == '-' {
		return false
	}
	for _, c := range []byte(kind) {
		if (c < 'a' || c > 'z') && c != '-' {
			return false
		}
	}
	return true
}

// templateOK admits a positive decimal without a leading zero, so one
// template version has one spelling.
func templateOK(number string) (int, bool) {
	if number == "" || number[0] == '0' {
		return 0, false
	}
	for _, c := range []byte(number) {
		if c < '0' || c > '9' {
			return 0, false
		}
	}
	n, err := strconv.Atoi(number)
	return n, err == nil
}
