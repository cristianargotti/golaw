const (
	handwritten = "package x\n\n// F is written by a person.\nfunc F() {}\n"
	sqlcOutput  = "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.31.1\n\npackage sqlcgen\n"
	golawOutput = "// Code generated by golaw 0.3.0 kind=support@1; DO NOT EDIT.\n\npackage gensupport\n"
)

func layoutTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, content := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func declared(edit func(*model.GeneratePolicy)) model.GeneratePolicy {
	g := model.DefaultGenerate()
	g.Declared = true
	edit(&g)
	return g
}

func TestDetectGenerateReadsTheHandWrittenPackages(t *testing.T) {
	t.Parallel()
	outbound := func(g *model.GeneratePolicy) {
		g.Layout.AdapterSQL = "internal/adapters/outbound/{package}"
		g.Layout.AdapterHTTP = "internal/adapters/outbound/{package}"
		g.ThirdParty.SQLCOut = "internal/adapters/outbound/postgres/sqlcgen"
	}
	tests := map[string]struct {
		files map[string]string
		want  model.GeneratePolicy
	}{
		"an empty repository takes the defaults": {map[string]string{"go.mod": "module example.com/slice\n"}, declared(func(*model.GeneratePolicy) {})},
		"the pilot shape: out and in, outbound holds only sqlc output": {map[string]string{
			"internal/adapters/in/api/handler.go":               handwritten,
			"internal/adapters/in/jobs/job.go":                  handwritten,
			"internal/adapters/out/postgres/plans.go":           handwritten,
			"internal/adapters/out/meta/client.go":              handwritten,
			"internal/adapters/outbound/postgres/sqlcgen/db.go": sqlcOutput,
		}, declared(func(*model.GeneratePolicy) {})},
		"outbound and inbound alone": {map[string]string{
			"internal/adapters/outbound/postgres/plans.go": handwritten,
			"internal/adapters/inbound/api/handler.go":     handwritten,
		}, declared(func(g *model.GeneratePolicy) {
			outbound(g)
			g.Layout.Handler = "internal/adapters/inbound/{package}"
		})},
		"near: a golaw generated directory under out is no adapter": {map[string]string{
			"internal/adapters/out/gensupport/zz_generated_hole.go": golawOutput,
			"internal/adapters/outbound/postgres/plans.go":          handwritten,
		}, declared(outbound)},
		"near: a test file alone makes no package": {map[string]string{
			"internal/adapters/out/postgres/plans_test.go": handwritten,
			"internal/adapters/outbound/postgres/plans.go": handwritten,
		}, declared(outbound)},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			got, err := bootstrap.DetectGenerate(layoutTree(t, tc.files))
			if err != nil {
				t.Fatal(err)
			}
			if got != tc.want {
				t.Errorf("DetectGenerate = %+v\nwant             %+v", got, tc.want)
			}
		})
	}
}

// The red row: hand written adapters under both out and outbound are
// never a silent choice.
func TestDetectGenerateRefusesTwoLayoutsForOneKind(t *testing.T) {
	t.Parallel()
	root := layoutTree(t, map[string]string{
		"internal/adapters/out/postgres/plans.go":   handwritten,
		"internal/adapters/outbound/meta/client.go": handwritten,
	})
	_, err := bootstrap.DetectGenerate(root)
	for _, want := range []string{"internal/adapters/out", "internal/adapters/outbound", "generate.layout.adapter_sql"} {
		if !errors.Is(err, bootstrap.ErrLayout) || !strings.Contains(err.Error(), want) {
			t.Errorf("DetectGenerate = %v, want ErrLayout naming %s", err, want)
		}
	}
}

func TestSetGenerateAppendsTheBlockOnceAndKeepsAReviewedOne(t *testing.T) {
	t.Parallel()
	g := declared(func(g *model.GeneratePolicy) { g.Layout.Handler = "internal/adapters/inbound/{package}" })
	out, err := bootstrap.SetGenerate([]byte(renderedCore), g)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(out), renderedCore) || !strings.Contains(string(out), "\ngenerate:\n  layout:\n    port: internal/application/{area}\n") {
		t.Fatalf("SetGenerate = %s", out)
	}
	f, err := policy.Decode(out)
	if err != nil || f.Generate.Resolve() != g {
		t.Fatalf("decoded block = %+v, %v, want %+v", f.Generate.Resolve(), err, g)
	}
	again, err := bootstrap.SetGenerate(out, declared(func(*model.GeneratePolicy) {}))
	if err != nil || !bytes.Equal(again, out) {
		t.Errorf("a reviewed block was rewritten: %v\n%s", err, again)
	}
	if _, err := bootstrap.SetGenerate([]byte("golaw: [\n"), g); err == nil {
		t.Error("a policy that does not decode answered no error")
	}
}
