// TestDeadcodeAssetLeavesTestSupportPackagesOut holds the test support
// package to its purpose: a package no production file imports serves
// tests, so its exports are no candidates, while one production importer
// makes every export of the package a candidate again.
func TestDeadcodeAssetLeavesTestSupportPackagesOut(t *testing.T) {
	t.Parallel()
	const support = "package testutil\n\nfunc Fixture() int { return 1 }\n\nfunc Other() int { return 2 }\n"
	const test = "package service\n\nimport (\n\t\"testing\"\n\n\t\"example.test/service/internal/testutil\"\n)\n\n" +
		"func TestValue(t *testing.T) { if testutil.Fixture()+testutil.Other() == 0 { t.Fatal(\"value\") } }\n"
	for _, tc := range []struct {
		name, source string
		want         int
	}{
		{"near imported by tests alone", "package service\n\nfunc Value() int { return 1 }\n", 0},
		{"red imported by production", "package service\n\nimport \"example.test/service/internal/testutil\"\n\nfunc Value() int { return testutil.Other() }\n", 1},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			out := runReachabilityFixture(t, map[string]string{
				"go.mod":                         "module example.test/service\n\ngo 1.27\n",
				"main.go":                        "package main\n\nimport \"example.test/service/internal/service\"\n\nfunc main() { _ = service.Value() }\n",
				"internal/service/value.go":      tc.source,
				"internal/service/value_test.go": test,
				"internal/testutil/testutil.go":  support,
			})
			if out.Code != tc.want {
				t.Fatalf("exit = %d, want %d: %s%s", out.Code, tc.want, out.Stdout, out.Stderr)
			}
			if tc.want == 1 && (!strings.Contains(string(out.Stdout), "Fixture") || strings.Contains(string(out.Stdout), "Other")) {
				t.Fatalf("the test-only export of an imported package is the one named: %s", out.Stdout)
			}
		})
	}
}

// TestDeadcodeAssetJudgesOnlyTheQueriesOfGeneratedCode holds generated code
// to what its developer controls: a method of a sqlc query file comes from a
// query the developer wrote, while sqlc's own boilerplate and the functions
// of any other generator come back on the next generate if removed.
func TestDeadcodeAssetJudgesOnlyTheQueriesOfGeneratedCode(t *testing.T) {
	t.Parallel()
	const header = "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.31.1\n"
	const db = header + "\npackage sqlcgen\n\ntype DBTX interface{ Exec() }\n\nfunc New(db DBTX) *Queries { return &Queries{db: db} }\n\n" +
		"type Queries struct{ db DBTX }\n\nfunc (q *Queries) WithTx(tx DBTX) *Queries { return &Queries{db: tx} }\n"
	const query = header + "// source: items.sql\n\npackage sqlcgen\n\nfunc (q *Queries) GetItem() int { return 1 }\n"
	const live = "package main\n\nimport \"example.test/service/internal/sqlcgen\"\n\nfunc main() { _ = sqlcgen.New(nil).GetItem() }\n"
	const oapi = "// Package api provides primitives.\n//\n// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.4.1 DO NOT EDIT.\npackage api\n\nfunc RegisterHandlers() {}\n"
	for _, tc := range []struct {
		name, main, api, want string
		code                  int
	}{
		{"near boilerplate of db.go", live, "", "", 0},
		{"red unused query", "package main\n\nfunc main() {}\n", "", "GetItem", 1},
		{"near function of another generator", live, oapi, "", 0},
		{"red handwritten function beside generated code", live, "package api\n\nfunc RegisterRoutes() {}\n", "RegisterRoutes", 1},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{
				"go.mod": "module example.test/service\n\ngo 1.27\n", "main.go": tc.main,
				"internal/sqlcgen/db.go": db, "internal/sqlcgen/items.sql.go": query,
			}
			if tc.api != "" {
				files["internal/api/server.gen.go"] = tc.api
			}
			out := runReachabilityFixture(t, files)
			stdout := string(out.Stdout)
			if out.Code != tc.code || !strings.Contains(stdout, tc.want) || strings.Contains(stdout, "WithTx") || strings.Contains(stdout, "New:") {
				t.Fatalf("exit = %d, want %d naming %q: %s%s", out.Code, tc.code, tc.want, out.Stdout, out.Stderr)
			}
		})
	}
}

// TestServiceFixturePassesItsDeadcodeAsset runs the rendered asset over the
// service rendered with every capability, as its make deadcode does, so the
// generated code of the fixture holds no candidate its developer cannot
// remove.
func TestServiceFixturePassesItsDeadcodeAsset(t *testing.T) {
	t.Parallel()
	root := writeTree(t, serviceFiles(t, []string{"api", "db", "go", "hexagonal", "image"}))
	env := append((&exec.Cmd{}).Environ(), "GOTOOLCHAIN=local", "GOFLAGS=-mod=mod", "GOWORK=off")
	out, err := runner.Run(t.Context(), runner.Command{
		Name: "go", Dir: root, Env: env,
		Args: []string{"test", "-count=1", "-tags=deadcode", "-run", "^TestProductionExportsHaveConsumers$", "./test/deadcode/"},
	})
	if err != nil || out.Code != 0 {
		t.Fatalf("deadcode over the service = %d: %s%s: %v", out.Code, out.Stdout, out.Stderr, err)
	}
}
