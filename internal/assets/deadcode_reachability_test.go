func runReachabilityFixture(t *testing.T, files map[string]string) runner.Output {
	t.Helper()
	root := t.TempDir()
	asset := renderedAsset(t, "test/deadcode/reachability_test.go", assetContext())
	if asset.Template.Ownership != assets.OwnedByDeveloper {
		t.Fatal("reachability asset must remain developer-owned")
	}
	files[asset.Path] = string(asset.Data)
	writeFixtures(t, root, files)
	env := append((&exec.Cmd{}).Environ(),
		"GOTOOLCHAIN=local", "GOPROXY=off", "GOSUMDB=off", "GOWORK=off")
	out, err := runner.Run(t.Context(), runner.Command{
		Name: "go", Dir: root, Env: env,
		Args: []string{"test", "-tags=deadcode", "-run", "^TestProductionExportsHaveConsumers$", "./test/deadcode/"},
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestDeadcodeAssetFindsOnlyUnconsumedProductionExports(t *testing.T) {
	t.Parallel()
	const module = "module example.test/service\n\ngo 1.27\n"
	const library = "package service\n\nfunc Value() int { return 1 }\n"
	const emptyMain = "package main\n\nfunc main() {}\n"
	const liveMain = "package main\n\nimport \"example.test/service/internal/service\"\n\nfunc main() { _ = service.Value() }\n"
	const testOnly = "package service\n\nimport \"testing\"\n\nfunc TestValue(t *testing.T) { if Value() != 1 { t.Fatal(\"value\") } }\n"
	for _, tc := range []struct {
		name, main, source, test string
		want                     int
	}{
		{"red no caller", emptyMain, library, "", 1},
		{"red test-only caller", emptyMain, library, testOnly, 1},
		{"near production caller", liveMain, library, "", 0},
		{"near function value", "package main\n\nimport \"example.test/service/internal/service\"\n\nfunc main() { value := service.Value; _ = value() }\n", library, "", 0},
		{"near unexported", emptyMain, "package service\n\nfunc value() int { return 1 }\n", "", 0},
		{"near interface method", emptyMain, "package service\n\nimport \"net/http\"\n\ntype Handler struct{}\n\nfunc (h Handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {}\n", "", 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{
				"go.mod":                    module,
				"main.go":                   tc.main,
				"internal/service/value.go": tc.source,
			}
			if tc.test != "" {
				files["internal/service/value_test.go"] = tc.test
			}
			out := runReachabilityFixture(t, files)
			if out.Code != tc.want {
				t.Fatalf("exit = %d, want %d: %s%s", out.Code, tc.want, out.Stdout, out.Stderr)
			}
			if tc.want == 1 && !strings.Contains(string(out.Stdout), "Value") {
				t.Fatalf("missing symbol repair: %s", out.Stdout)
			}
		})
	}
}

func TestDeadcodeAssetKeepsUncertainExternalConsumersOut(t *testing.T) {
	t.Parallel()
	out := runReachabilityFixture(t, map[string]string{
		"go.mod":          "module example.test/service\n\ngo 1.27\n",
		"main.go":         "package main\n\nfunc main() {}\n",
		"public/value.go": "package public\n\nfunc Value() int { return 1 }\n",
	})
	if out.Code != 0 {
		t.Fatalf("external API was called dead: %s%s", out.Stdout, out.Stderr)
	}
}

