package assets_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/cristianargotti/golaw/internal/runner"
)

func TestGitleaksScansGeneratedFiles(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name   string
		secret bool
		want   int
	}{
		{"red", true, 1},
		{"near", false, 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root, config := generatedRoot(t, tc.secret)
			result, err := runner.Run(t.Context(), runner.Command{
				Name: "gitleaks", Dir: root,
				Args: []string{"dir", "--config", config, "--redact", "--no-banner", "."},
			})
			if err != nil || result.Code != tc.want {
				t.Fatalf("gitleaks code = %d, error = %v", result.Code, err)
			}
		})
	}
}

// generatedRoot is a directory that holds the rendered gitleaks
// configuration and a generated Go file, with a token when secret is set.
func generatedRoot(t *testing.T, secret bool) (string, string) {
	t.Helper()
	root := t.TempDir()
	rendered := renderedAsset(t, ".gitleaks.toml", assetContext())
	config := filepath.Join(root, ".gitleaks.toml")
	if err := os.WriteFile(config, rendered.Data, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(root, "gen"), 0o700); err != nil {
		t.Fatal(err)
	}
	value := "public-example"
	if secret {
		value = strings.Join([]string{"gl", "pat", "-", "1234567890abcdefghijAB"}, "")
	}
	content := "// Code generated by sample. DO NOT EDIT.\npackage gen\nconst value = \"" + value + "\"\n"
	path := filepath.Join(root, "gen", "generated.go")
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return root, config
}
