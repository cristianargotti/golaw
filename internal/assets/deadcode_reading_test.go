// runReadingFixture compiles the asset once against a valid module, then
// runs that binary over fixtures that need not type-check, because the
// asset only parses the files it judges.
func runReadingFixture(t *testing.T, files map[string]string, changes ...func(string)) runner.Output {
	t.Helper()
	root := t.TempDir()
	asset := renderedAsset(t, "test/deadcode/reachability_test.go", assetContext())
	writeFixtures(t, root, map[string]string{"go.mod": "module example.test/service\n\ngo 1.27\n", asset.Path: string(asset.Data)})
	env := append((&exec.Cmd{}).Environ(), "GOTOOLCHAIN=local", "GOPROXY=off", "GOSUMDB=off", "GOWORK=off")
	binary := filepath.Join(root, "reading-test")
	// Windows starts a program only by its .exe name.
	if runtime.GOOS == "windows" {
		binary += ".exe"
	}
	built, err := runner.Run(t.Context(), runner.Command{Name: "go", Dir: root, Env: env, Args: []string{"test", "-c", "-tags=deadcode", "-o", binary, "./test/deadcode/"}})
	if err != nil || built.Code != 0 {
		t.Fatalf("compile fixture: %v: %s%s", err, built.Stdout, built.Stderr)
	}
	if removeErr := os.Remove(filepath.Join(root, "go.mod")); removeErr != nil {
		t.Fatal(removeErr)
	}
	writeFixtures(t, root, files)
	for _, change := range changes {
		change(root)
	}
	out, err := runner.Run(t.Context(), runner.Command{Name: binary, Dir: filepath.Join(root, "test", "deadcode"), Env: env, Args: []string{"-test.v", "-test.run", "^TestProductionExportsHaveConsumers$"}})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestDeadcodeAssetDoesNotCountDeclarationNames(t *testing.T) {
	t.Parallel()
	for _, source := range []string{
		"package main\nfunc Value() {}\n",
		"package main\ntype Value struct{}\n",
		"package main\nvar Value int\n",
		"package main\ntype item struct { Value int }\n",
		"package main\nfunc use(Value int) {}\n",
		"package main\nfunc use() (Value int) { return }\n",
		"package main\nfunc use[Value any]() {}\n",
		"package main\nfunc main() { Value := 1 }\n",
		"package main\nfunc main() { for Value := range []int{} {} }\n",
		"package main\nimport Value \"fmt\"\n",
		"package Value\n",
		"package main\nfunc main() { Value: for { break } }\n",
	} {
		t.Run(source, func(t *testing.T) {
			t.Parallel()
			out := runReadingFixture(t, map[string]string{
				"go.mod":                    "module example.test/service\n\ngo 1.27\n",
				"main.go":                   source,
				"internal/service/value.go": "package service\nfunc Value() int { return 1 }\n",
			})
			if out.Code != 1 || !strings.Contains(string(out.Stdout), "Value") || strings.Contains(string(out.Stdout), "cannot measure") {
				t.Fatalf("declaration counted as a consumer: %d: %s%s", out.Code, out.Stdout, out.Stderr)
			}
		})
	}
}

func TestDeadcodeAssetMatchesGeneratedReceiversByDirectory(t *testing.T) {
	t.Parallel()
	const header = "// Code generated by sqlc. DO NOT EDIT.\n"
	const receiver = "package query\ntype Queries struct{}\n"
	const method = header + "// source: query.sql\npackage query\nfunc (q *Queries) Lookup() int { return 1 }\n"
	for _, tc := range []struct {
		name, types, methodPath, method string
		want                            int
	}{
		{"separate file", header + receiver, "internal/query/method.go", method, 1},
		{"separate package", header + receiver, "internal/other/method.go", method, 0},
		{"late marker", receiver + header, "internal/query/method.go", method, 0},
		{"different generator", "// Code generated by another tool. DO NOT EDIT.\n" + receiver, "internal/query/method.go", method, 0},
		{"local type", header + "package query\nvar _ = func() { type Queries struct{} }\n", "internal/query/method.go", method, 0},
		{"generic receiver", header + "package query\ntype Queries[T any] struct{}\n", "internal/query/method.go", header + "// source: query.sql\npackage query\nfunc (q *Queries[T]) Lookup() int { return 1 }\n", 1},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			out := runReadingFixture(t, map[string]string{
				"go.mod":                  "module example.test/service\n\ngo 1.27\n",
				"main.go":                 "package main\nfunc main() {}\n",
				"internal/query/types.go": tc.types,
				tc.methodPath:             tc.method,
			})
			if out.Code != tc.want || tc.want == 1 && !strings.Contains(string(out.Stdout), "Lookup") {
				t.Fatalf("generated receiver = %d, want %d: %s%s", out.Code, tc.want, out.Stdout, out.Stderr)
			}
		})
	}
}

func TestDeadcodeAssetExcludesNonProductionTrees(t *testing.T) {
	t.Parallel()
	for _, dir := range []string{"internal/testdata", "internal/fixtures", "internal/.hidden", "internal/vendor", "tools", "nested"} {
		t.Run(dir, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{
				"go.mod":                    "module example.test/service\n\ngo 1.27\n",
				"main.go":                   "package main\nfunc main() {}\n",
				"internal/service/value.go": "package service\nfunc Value() int { return 1 }\n",
				dir + "/consumer.go":        "package ignored\nfunc caller() { Value() }\n",
				dir + "/broken.go":          "package ignored\nfunc Broken(\n",
			}
			if dir == "tools" || dir == "nested" {
				files[dir+"/go.mod"] = "module example.test/isolated\n\ngo 1.27\n"
			}
			out := runReadingFixture(t, files)
			if out.Code != 1 || !strings.Contains(string(out.Stdout), "Value") || strings.Contains(string(out.Stdout), "cannot measure") {
				t.Fatalf("excluded tree changed the conclusion: %d: %s%s", out.Code, out.Stdout, out.Stderr)
			}
		})
	}
}

func TestDeadcodeAssetStatesUnreadableProductionLimits(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, main string
		want       int
	}{
		{"parse error", "package main\nfunc broken(\n", 1},
		{"literal reflection", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.ValueOf(nil).MethodByName(\"Lookup\") }\n", 0},
		{"dynamic reflection", "package main\nimport \"reflect\"\nfunc main() { name := \"Lookup\"; _ = reflect.ValueOf(nil).MethodByName(name) }\n", 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			out := runReadingFixture(t, map[string]string{
				"go.mod":                  "module example.test/service\n\ngo 1.27\n",
				"main.go":                 tc.main,
				"internal/query/query.go": "// Code generated by sqlc. DO NOT EDIT.\n// source: query.sql\npackage query\ntype Queries struct{}\nfunc (q *Queries) Lookup() int { return 1 }\n",
			})
			if out.Code != tc.want {
				t.Fatalf("reading = %d, want %d: %s%s", out.Code, tc.want, out.Stdout, out.Stderr)
			}
			if tc.want == 1 && (!strings.Contains(string(out.Stdout), "cannot measure production consumers") || strings.Contains(string(out.Stdout), "Lookup")) {
				t.Fatalf("a reading limit became a dead-symbol conclusion: %s%s", out.Stdout, out.Stderr)
			}
			if tc.want == 0 && (strings.Count(string(out.Stdout), "dynamic method lookup: the generated query methods are not judged") != 1 || strings.Contains(string(out.Stdout), "Lookup") || strings.Contains(string(out.Stdout), "cannot measure") || strings.Contains(string(out.Stdout), "SKIP")) {
				t.Fatalf("dynamic reflection was not limited once: %s%s", out.Stdout, out.Stderr)
			}
		})
	}
}

func TestDeadcodeAssetDoesNotFollowExternalSourceLinks(t *testing.T) {
	t.Parallel()
	out := runReadingFixture(t, map[string]string{
		"go.mod":                  "module example.test/service\n\ngo 1.27\n",
		"internal/query/query.go": "// Code generated by sqlc. DO NOT EDIT.\n// source: query.sql\npackage query\ntype Queries struct{}\nfunc (q *Queries) Lookup() int { return 1 }\n",
	}, func(root string) {
		external := filepath.Join(t.TempDir(), "consumer.go")
		if err := os.WriteFile(external, []byte("package main\nfunc main() { Lookup() }\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(external, filepath.Join(root, "main.go")); err != nil {
			t.Fatal(err)
		}
	})
	if out.Code != 1 || !strings.Contains(string(out.Stdout), "cannot measure production consumers") || strings.Contains(string(out.Stdout), "Lookup") {
		t.Fatalf("external source link changed the conclusion: %d: %s%s", out.Code, out.Stdout, out.Stderr)
	}
}

func TestDeadcodeAssetKeepsDynamicLimitsPrecise(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, source, ignored string
		want                  int
		limited, function     bool
	}{
		{"method value", "package main\nimport \"reflect\"\nfunc main() { lookup := reflect.ValueOf(nil).MethodByName; _ = lookup(\"Lookup\") }\n", "", 0, true, false},
		{"ordinary Method", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.DeepEqual(1, 1); router.Method(\"GET\") }\n", "", 0, true, false},
		{"ordinary MethodByName", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.DeepEqual(1, 1); router.MethodByName(name); query.Lookup() }\n", "", 0, true, false},
		{"ordinary Lookup", "package main\nimport \"plugin\"\nfunc main() { _ = plugin.Open; query.Lookup(1) }\n", "", 0, false, false},
		{"hidden file", "package main\nfunc main() { _ = query.Lookup }\n", "internal/query/.hidden.go", 0, false, false},
		{"ignored file", "package main\nfunc main() { _ = query.Lookup }\n", "internal/query/_ignored.go", 0, false, false},
		{"field access", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.DeepEqual; _ = request.Method }\n", "", 1, false, false},
		{"literal unknown receiver", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.DeepEqual; request.MethodByName(\"Lookup\") }\n", "", 0, true, false},
		{"without reflect", "package main\nfunc main() { request.MethodByName(name) }\n", "", 1, false, false},
		{"two arguments", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.DeepEqual; request.MethodByName(\"Lookup\", 1) }\n", "", 0, true, false},
		{"one limit functions judged", "package main\nimport \"reflect\"\nfunc main() { _ = reflect.DeepEqual; request.MethodByName(name); request.Method(0) }\n", "", 1, true, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{
				"go.mod": "module example.test/service\n\ngo 1.27\n", "main.go": tc.source,
				"internal/query/query.go": "// Code generated by sqlc. DO NOT EDIT.\n// source: query.sql\npackage query\ntype Queries struct{}\nfunc (q *Queries) Lookup() int { return 1 }\n",
			}
			if tc.ignored != "" {
				files[tc.ignored] = "package query\nfunc Ignored() {}\n"
			}
			if tc.function {
				files["internal/query/orphan.go"] = "package query\nfunc Orphan() {}\n"
			}
			out := runReadingFixture(t, files)
			assertDynamicReading(t, out, tc.want, tc.limited, tc.function)
		})
	}
}

func TestDeadcodeAssetReadsTheRuntimeModule(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, directive, module, testPath string
		want                              int
	}{
		{"renamed", "module example.test/renamed", "example.test/renamed", "internal/tests/support_test.go", 0},
		{"quoted", "module \"example.test/renamed\"", "example.test/renamed", "internal/tests/support_test.go", 0},
		{"backquoted", "module `example.test/renamed`", "example.test/renamed", "internal/tests/support_test.go", 0},
		{"trailing comment", "  module \"example.test/renamed\" // selected module", "example.test/renamed", "internal/tests/support_test.go", 0},
		{"external own directory", "module example.test/renamed", "example.test/renamed", "internal/helper/helper_test.go", 1},
		{"quoted current module", "module \"example.test/service\" // comment", "example.test/service", "internal/tests/support_test.go", 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			out := runReadingFixture(t, map[string]string{
				"go.mod":                    tc.directive + "\n\ngo 1.27\n",
				"internal/helper/helper.go": "package helper\nfunc Fixture() {}\n",
				tc.testPath:                 "package helper_test\nimport \"" + tc.module + "/internal/helper\"\nfunc use() { helper.Fixture() }\n",
			})
			if out.Code != tc.want || tc.want == 1 && !strings.Contains(string(out.Stdout), "Fixture:") {
				t.Fatalf("runtime module = %d, want %d: %s%s", out.Code, tc.want, out.Stdout, out.Stderr)
			}
		})
	}
}

func TestDeadcodeAssetStatesModuleReadFailures(t *testing.T) {
	t.Parallel()
	for _, state := range []string{"missing", "empty", "no directive", "unreadable"} {
		t.Run(state, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"internal/helper/helper.go": "package helper\nfunc Fixture() {}\n"}
			if state == "empty" {
				files["go.mod"] = ""
			}
			if state == "no directive" {
				files["go.mod"] = "go 1.27\n"
			}
			out := runReadingFixture(t, files, func(root string) {
				if state == "unreadable" {
					makeUnreadableModule(t, root)
				}
			})
			if out.Code != 1 || !strings.Contains(string(out.Stdout), "cannot measure production consumers") || strings.Contains(string(out.Stdout), "Fixture:") {
				t.Fatalf("module reading failure = %d: %s%s", out.Code, out.Stdout, out.Stderr)
			}
		})
	}
}

func TestDeadcodeAssetKeepsOwnPackageTestsAsTestOnlyConsumers(t *testing.T) {
	t.Parallel()
	out := runReadingFixture(t, map[string]string{
		"go.mod":                         "module example.test/service\n\ngo 1.27\n",
		"internal/service/value.go":      "package service\nfunc Value() int { return 1 }\n",
		"internal/service/value_test.go": "package service_test\nimport \"example.test/service/internal/service\"\nfunc use() { _ = service.Value() }\n",
	})
	if out.Code != 1 || !strings.Contains(string(out.Stdout), "Value:") || strings.Contains(string(out.Stdout), "cannot measure") {
		t.Fatalf("external same-directory test became production support: %d: %s%s", out.Code, out.Stdout, out.Stderr)
	}
}

func assertDynamicReading(t *testing.T, out runner.Output, want int, limited, function bool) {
	t.Helper()
	message := string(out.Stdout)
	limit := strings.Count(message, "dynamic method lookup: the generated query methods are not judged")
	if out.Code != want || (limit == 1) != limited || limit > 1 || strings.Contains(message, "cannot measure") || strings.Contains(message, "SKIP") {
		t.Fatalf("consumer certainty = %d: %s%s", out.Code, out.Stdout, out.Stderr)
	}
	if limited && strings.Contains(message, "Lookup:") || function && !strings.Contains(message, "Orphan:") || want == 1 && !function && !strings.Contains(message, "Lookup:") {
		t.Fatalf("incorrect candidate withholding: %s", message)
	}
}

func makeUnreadableModule(t *testing.T, root string) {
	t.Helper()
	if err := os.Mkdir(filepath.Join(root, "go.mod"), 0o700); err != nil {
		t.Fatal(err)
	}
}
