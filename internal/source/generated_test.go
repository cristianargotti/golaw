package source_test

import (
	"testing"

	"github.com/cristianargotti/golaw/internal/model"
	"github.com/cristianargotti/golaw/internal/source"
)

func TestClassifyReadsTheGeneratedHeaderGeneratorsWrite(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, content string
		want          model.FileClass
	}{
		{"red swaggo header", "// Package api Code generated by swaggo/swag. DO NOT EDIT\npackage api\n", model.ClassGenerated},
		{"red convention", "// Code generated by mockery. DO NOT EDIT.\npackage mocks\n", model.ClassGenerated},
		{"red without the period", "// Code generated by sqlc. DO NOT EDIT\npackage db\n", model.ClassGenerated},
		{"near prose", "// Package api wraps code generated by swaggo; do not edit the generated files.\npackage api\n", model.ClassTracked},
		{"near inside a sentence", "// This mentions Code generated by x. DO NOT EDIT.\npackage api\n", model.ClassTracked},
		{"near block comment", "/* Code generated by x. DO NOT EDIT. */\npackage api\n", model.ClassTracked},
	} {
		if got := source.Classify("api/docs.go", []byte(tc.content), true); got != tc.want {
			t.Fatalf("%s: class = %v, want %v", tc.name, got, tc.want)
		}
	}
}
