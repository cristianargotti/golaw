// indexOf freezes the index of the repository that holds root.
func indexOf(t *testing.T, root string, opts source.IndexOptions) *source.Index {
	t.Helper()
	repo, err := source.Discover(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	x, err := source.NewIndex(t.Context(), repo, opts)
	if err != nil {
		t.Fatal(err)
	}
	return x
}

// readText answers the bytes a snapshot holds at a path, or fails the test.
func readText(t *testing.T, s model.Snapshot, rel string) string {
	t.Helper()
	data, err := s.Read(rel)
	if err != nil {
		t.Fatalf("read %s: %v", rel, err)
	}
	return string(data)
}

// pathsOf lists the paths of files in their order.
func pathsOf(files []model.File) []string {
	out := make([]string, 0, len(files))
	for _, f := range files {
		out = append(out, f.Path)
	}
	return out
}

func TestIndexReadsTheStagedBlobsNeverTheWorktree(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Commit("feat: base", map[string]string{"a.txt": "one\n", "gone.txt": "gone\n", "deleted.txt": "deleted\n"})
	r.StageOnly("a.txt", "two\n", "three\n")
	r.Remove("gone.txt")
	r.StageDeletion("deleted.txt")
	r.Write("deleted.txt", "back on disk\n")
	r.Write("untracked.txt", "untracked\n")
	x := indexOf(t, r.Root, source.IndexOptions{})
	if got := readText(t, x, "a.txt"); got != "two\n" {
		t.Errorf("a.txt = %q, want the staged two", got)
	}
	if got := readText(t, x, "gone.txt"); got != "gone\n" {
		t.Errorf("gone.txt = %q, want the blob the index still holds", got)
	}
	for _, rel := range []string{"deleted.txt", "untracked.txt", "absent.txt"} {
		if _, err := x.Read(rel); !errors.Is(err, model.ErrNotInSnapshot) {
			t.Errorf("%s: %v, want ErrNotInSnapshot", rel, err)
		}
		if got := x.Class(rel); got != model.ClassUnknown {
			t.Errorf("%s has the class %s", rel, got)
		}
	}
	want := []model.File{{Path: "a.txt", Class: model.ClassTracked, Size: 4}, {Path: "gone.txt", Class: model.ClassTracked, Size: 5}}
	if got := x.Files(); !slices.Equal(got, want) {
		t.Errorf("files = %+v, want %+v", got, want)
	}
	if x.Root() != r.Root {
		t.Errorf("root = %s, want %s", x.Root(), r.Root)
	}
}

func TestIndexClassifiesEveryEntryFromItsModeAndBlob(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Stage(map[string]string{
		"main.go":           "package main\n",
		"main_test.go":      "package main\n",
		"testdata/case.txt": "fixture\n",
		"gen.go":            "// Code generated by hand. DO NOT EDIT.\npackage main\n",
		"image.bin":         "\x00\x01",
		"target.txt":        "main.go",
	})
	link := r.Git("rev-parse", ":target.txt")
	r.Git("update-index", "--add", "--cacheinfo", "120000,"+link+",link")
	r.Git("update-index", "--add", "--cacheinfo", "160000,"+strings.Repeat("1", 40)+",sub")
	r.Git("update-index", "--add", "--cacheinfo", "100644,"+strings.Repeat("2", 40)+",ghost.txt")
	x := indexOf(t, r.Root, source.IndexOptions{})
	for rel, want := range map[string]model.FileClass{
		"main.go": model.ClassTracked, "main_test.go": model.ClassTest, "testdata/case.txt": model.ClassFixture,
		"gen.go": model.ClassGenerated, "image.bin": model.ClassBinary, "link": model.ClassSymlink,
		"sub": model.ClassGitlink, "ghost.txt": model.ClassUnreadable,
	} {
		if got := x.Class(rel); got != want {
			t.Errorf("%s = %s, want %s", rel, got, want)
		}
	}
	for _, rel := range []string{"link", "sub", "ghost.txt"} {
		if _, err := x.Read(rel); !errors.Is(err, model.ErrUnreadable) {
			t.Errorf("%s: %v, want ErrUnreadable", rel, err)
		}
	}
	if got := readText(t, x, "image.bin"); got != "\x00\x01" {
		t.Errorf("image.bin = %q", got)
	}
	if got := x.Files(); len(got) != 9 || got[3].Path != "link" || got[3].Size != int64(len("main.go")) {
		t.Errorf("files = %+v", got)
	}
}

func TestIndexKeepsABlobOverTheBoundUnread(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Stage(map[string]string{"big.txt": strings.Repeat("a", model.MaxReadBytes+1)})
	x := indexOf(t, r.Root, source.IndexOptions{})
	if got := x.Files(); len(got) != 1 || got[0].Class != model.ClassTracked || got[0].Size != model.MaxReadBytes+1 {
		t.Errorf("files = %+v", got)
	}
	if _, err := x.Read("big.txt"); !errors.Is(err, model.ErrTooLarge) {
		t.Errorf("read = %v, want ErrTooLarge", err)
	}
	if _, err := x.Blob(r.Git("rev-parse", ":big.txt")); !errors.Is(err, model.ErrTooLarge) {
		t.Errorf("blob = %v, want ErrTooLarge", err)
	}
}

func TestIndexLeavesOutIntentsToAddAndUnmergedPaths(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Commit("feat: base", map[string]string{"shared.md": "base\n"})
	r.Branch("side", map[string]string{"shared.md": "theirs\n"})
	r.Commit("feat: ours", map[string]string{"shared.md": "ours\n", "kept.md": "kept\n"})
	r.MergeInProgress("side")
	r.Write("intent.md", "intent\n")
	r.Write("gone.png", "png\n")
	r.Git("add", "-N", "intent.md", "gone.png")
	r.Remove("gone.png")
	r.Stage(map[string]string{"empty.md": ""})
	x := indexOf(t, r.Root, source.IndexOptions{})
	if got, want := pathsOf(x.Files()), []string{"empty.md", "kept.md"}; !slices.Equal(got, want) {
		t.Errorf("files = %v, want %v", got, want)
	}
	if got := readText(t, x, "empty.md"); got != "" {
		t.Errorf("empty.md = %q", got)
	}
	for _, rel := range []string{"intent.md", "gone.png", "shared.md"} {
		if got := x.Class(rel); got != model.ClassUnknown {
			t.Errorf("%s has the class %s", rel, got)
		}
	}
}

func TestIndexReadsTheIndexOfALinkedWorktreeAndAnAlternateIndex(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Commit("feat: base", map[string]string{"a.txt": "a\n"})
	w := r.Worktree("feature")
	w.Stage(map[string]string{"feature.txt": "feature\n"})
	alternate := r.AlternateIndex()
	r.Write("alternate.txt", "alternate\n")
	r.GitEnv([]string{"GIT_INDEX_FILE=" + alternate}, "add", "alternate.txt")
	cases := map[string]struct {
		root string
		opts source.IndexOptions
		want []string
	}{
		"the repository's index": {r.Root, source.IndexOptions{}, []string{"a.txt"}},
		"a linked worktree":      {w.Root, source.IndexOptions{}, []string{"a.txt", "feature.txt"}},
		"an alternate index":     {r.Root, source.IndexOptions{IndexFile: alternate}, []string{"a.txt", "alternate.txt"}},
	}
	for name, tc := range cases {
		if got := pathsOf(indexOf(t, tc.root, tc.opts).Files()); !slices.Equal(got, tc.want) {
			t.Errorf("%s: files = %v, want %v", name, got, tc.want)
		}
	}
}

func TestIndexSelectsPartOfItsUniverse(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Stage(map[string]string{"cmd/a.go": "package a\n", "cmd/b.go": "package a\n", "docs/c.md": "c\n"})
	x := indexOf(t, r.Root, source.IndexOptions{})
	under := func(prefix string) func(string) bool {
		return func(p string) bool { return strings.HasPrefix(p, prefix) }
	}
	if got := pathsOf(x.Select(under("cmd/"))); !slices.Equal(got, []string{"cmd/a.go", "cmd/b.go"}) {
		t.Errorf("select = %v", got)
	}
	if !x.Any(under("docs/")) || x.Any(under("internal/")) {
		t.Error("Any names the paths of the universe only")
	}
	if got := pathsOf(model.Select(x, under("docs/"))); !slices.Equal(got, []string{"docs/c.md"}) {
		t.Errorf("model.Select = %v", got)
	}
}

func TestIndexIdentityAndBlobsByObjectID(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Commit("feat: base", map[string]string{"a.txt": "one\n"})
	before := indexOf(t, r.Root, source.IndexOptions{})
	again := indexOf(t, r.Root, source.IndexOptions{})
	r.Stage(map[string]string{"a.txt": "two\n"})
	after := indexOf(t, r.Root, source.IndexOptions{})
	if !strings.HasPrefix(before.Identity(), "index:") || before.Identity() != again.Identity() || before.Identity() == after.Identity() {
		t.Errorf("identities %s, %s, %s", before.Identity(), again.Identity(), after.Identity())
	}
	old := r.Git("rev-parse", "HEAD:a.txt")
	if got, err := model.ReadBlob(after, old); err != nil || string(got) != "one\n" {
		t.Errorf("the blob HEAD holds = %q, %v", got, err)
	}
	for id, want := range map[string]error{
		"HEAD:a.txt":                      model.ErrNotInSnapshot,
		strings.Repeat("3", 40):           model.ErrNotInSnapshot,
		r.Git("rev-parse", "HEAD^{tree}"): model.ErrUnreadable,
	} {
		if _, err := after.Blob(id); !errors.Is(err, want) {
			t.Errorf("blob %s: %v, want %v", id, err, want)
		}
	}
}

func TestIndexMarksWhatGitCannotAnswerUnreadable(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	r.Commit("feat: base", map[string]string{"a.txt": "a\n"})
	repo, err := source.Discover(t.Context(), r.Root)
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(t.Context())
	x, err := source.NewIndex(ctx, repo, source.IndexOptions{})
	if err != nil {
		t.Fatal(err)
	}
	cancel()
	if got := x.Class("a.txt"); got != model.ClassUnreadable {
		t.Errorf("a.txt after the context ended = %s", got)
	}
	if _, err := x.Read("a.txt"); !errors.Is(err, model.ErrUnreadable) {
		t.Errorf("read = %v, want ErrUnreadable", err)
	}
	if _, err := x.Blob(r.Git("rev-parse", "HEAD:a.txt")); !errors.Is(err, model.ErrUnreadable) || !errors.Is(err, source.ErrGit) {
		t.Errorf("blob = %v, want ErrUnreadable from ErrGit", err)
	}
}

func TestNewIndexFailsWhenGitCannotListTheIndex(t *testing.T) {
	t.Parallel()
	r := gittest.New(t)
	repo, err := source.Discover(t.Context(), r.Root)
	if err != nil {
		t.Fatal(err)
	}
	corrupt := filepath.Join(t.TempDir(), "index")
	if err := os.WriteFile(corrupt, []byte("not an index"), 0o600); err != nil {
		t.Fatal(err)
	}
	cases := map[string]struct {
		repo source.Repo
		opts source.IndexOptions
	}{
		"outside git":     {source.Repo{Root: t.TempDir()}, source.IndexOptions{}},
		"a corrupt index": {repo, source.IndexOptions{IndexFile: corrupt}},
	}
	for name, tc := range cases {
		if _, err := source.NewIndex(t.Context(), tc.repo, tc.opts); !errors.Is(err, source.ErrGit) {
			t.Errorf("%s: %v, want ErrGit", name, err)
		}
	}
}
