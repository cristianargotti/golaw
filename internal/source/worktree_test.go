// classes is the universe of a repository holding one file per class.
func classes(t *testing.T) (string, source.Repo) {
	t.Helper()
	root := initRepo(t)
	write(t, root, ".gitignore", "*.log\n")
	write(t, root, "a.go", "package a\n")
	write(t, root, "a_test.go", "package a\n")
	write(t, root, "testdata/f.txt", "x\n")
	write(t, root, "gen.go", "// Code generated by x. DO NOT EDIT.\npackage a\n")
	write(t, root, "blob.bin", "bin\x00ary")
	write(t, root, "empty.txt", "")
	write(t, root, "ignored.log", "l\n")
	commitAll(t, root, "one")
	write(t, root, "untracked.go", "package a\n")
	write(t, root, "nested/n.txt", "n\n")
	gitRun(t, filepath.Join(root, "nested"), "init", "-q")
	repo, err := source.Discover(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	return root, repo
}

func TestNewWorktreeClasses(t *testing.T) {
	t.Parallel()
	_, repo := classes(t)
	w, err := source.NewWorktree(t.Context(), repo)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]model.FileClass{
		".gitignore": model.ClassTracked, "a.go": model.ClassTracked, "a_test.go": model.ClassTest,
		"testdata/f.txt": model.ClassFixture, "gen.go": model.ClassGenerated, "blob.bin": model.ClassBinary,
		"empty.txt": model.ClassTracked, "untracked.go": model.ClassUntracked, "nested": model.ClassGitlink,
	}
	files := w.Files()
	if len(files) != len(want) {
		t.Fatalf("Files() = %+v", files)
	}
	for i, f := range files {
		if want[f.Path] != f.Class || (i > 0 && files[i-1].Path > f.Path) {
			t.Errorf("file %d = %+v, want class %s in path order", i, f, want[f.Path])
		}
	}
	if w.Class("ignored.log") != model.ClassUnknown || w.Class("a.go") != model.ClassTracked {
		t.Error("Class is wrong")
	}
	if w.Root() != repo.Root || len(w.Identity()) != 64 {
		t.Errorf("Root %q Identity %q", w.Root(), w.Identity())
	}
}

func TestWorktreeReadIsFrozen(t *testing.T) {
	t.Parallel()
	root, repo := classes(t)
	w, err := source.NewWorktree(t.Context(), repo)
	if err != nil {
		t.Fatal(err)
	}
	write(t, root, "a.go", "package changed\n")
	data, err := w.Read("a.go")
	if err != nil || string(data) != "package a\n" {
		t.Errorf("Read after a change on disk = %q, %v", data, err)
	}
	data[0] = 'X'
	if mustRead(t, w, "a.go") != "package a\n" {
		t.Error("Read must return a copy")
	}
	if mustRead(t, w, "empty.txt") != "" {
		t.Error("an empty file reads as empty bytes")
	}
	if mustRead(t, w, "blob.bin") != "bin\x00ary" {
		t.Error("binary bytes are readable")
	}
	if got := readErr(w, "ignored.log"); !errors.Is(got, model.ErrNotInSnapshot) {
		t.Errorf("ignored path: %v", got)
	}
	if got := readErr(w, "nested"); !errors.Is(got, model.ErrUnreadable) {
		t.Errorf("gitlink: %v", got)
	}
	again, err := source.NewWorktree(t.Context(), repo)
	if err != nil || again.Identity() == w.Identity() {
		t.Errorf("identity must follow the content: %v", err)
	}
}

func TestWorktreeLinksAndSubmodules(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("symbolic links need a privilege on Windows")
	}
	root := initRepo(t)
	write(t, root, "dir/a.txt", "a\n")
	if err := os.Symlink("dir/a.txt", filepath.Join(root, "link")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(t.TempDir(), filepath.Join(root, "linkdir")); err != nil {
		t.Fatal(err)
	}
	other := initRepo(t)
	write(t, other, "o.txt", "o\n")
	commitAll(t, other, "other")
	gitRun(t, root, "-c", "protocol.file.allow=always", "submodule", "add", "-q", other, "sub")
	commitAll(t, root, "one")
	repo, err := source.Discover(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	w, err := source.NewWorktree(t.Context(), repo)
	if err != nil {
		t.Fatal(err)
	}
	if w.Class("link") != model.ClassSymlink || w.Class("linkdir") != model.ClassSymlink || w.Class("sub") != model.ClassGitlink {
		t.Errorf("Files() = %+v", w.Files())
	}
	if w.Class("sub/o.txt") != model.ClassUnknown {
		t.Error("a submodule's files are not in the universe")
	}
	if err := readErr(w, "link"); !errors.Is(err, model.ErrUnreadable) {
		t.Errorf("a link is never followed: %v", err)
	}
}

func TestWorktreeNeverReadsThroughALinkedDirectory(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("symbolic links need a privilege on Windows")
	}
	root := initRepo(t)
	write(t, root, "dir/a.go", "package a\n")
	write(t, root, "ok/b.go", "package ok\n")
	commitAll(t, root, "one")
	outside := t.TempDir()
	write(t, outside, "a.go", "outside bytes\n")
	if err := os.RemoveAll(filepath.Join(root, "dir")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(root, "dir")); err != nil {
		t.Fatal(err)
	}
	repo, err := source.Discover(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	w, err := source.NewWorktree(t.Context(), repo)
	if err != nil {
		t.Fatal(err)
	}
	if w.Class("dir") != model.ClassSymlink || w.Class("dir/a.go") != model.ClassUnreadable {
		t.Errorf("a tracked path under a linked directory: Files() = %+v", w.Files())
	}
	if data, err := w.Read("dir/a.go"); !errors.Is(err, model.ErrUnreadable) {
		t.Errorf("Read(dir/a.go) = %q, %v: the link must never be followed", data, err)
	}
	if w.Class("ok/b.go") != model.ClassTracked || mustRead(t, w, "ok/b.go") != "package ok\n" {
		t.Errorf("a path under an ordinary directory is read: %+v", w.Files())
	}
}

func TestWorktreeUnreadableAndOversized(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" || os.Getuid() == 0 {
		t.Skip("permission bits do not refuse the owner here")
	}
	root := initRepo(t)
	write(t, root, "big.txt", strings.Repeat("x", model.MaxReadBytes+1))
	write(t, root, "big_test.go", strings.Repeat("x", model.MaxReadBytes+1))
	write(t, root, "secret.txt", "s\n")
	if err := os.Chmod(filepath.Join(root, "secret.txt"), 0o000); err != nil {
		t.Fatal(err)
	}
	repo, err := source.Discover(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	w, err := source.NewWorktree(t.Context(), repo)
	if err != nil {
		t.Fatal(err)
	}
	if w.Class("big.txt") != model.ClassUntracked || w.Class("big_test.go") != model.ClassTest || w.Class("secret.txt") != model.ClassUnreadable {
		t.Errorf("Files() = %+v", w.Files())
	}
	if err := readErr(w, "big.txt"); !errors.Is(err, model.ErrTooLarge) {
		t.Errorf("oversized: %v", err)
	}
	if err := readErr(w, "secret.txt"); !errors.Is(err, model.ErrUnreadable) {
		t.Errorf("unreadable: %v", err)
	}
}

// bulk is n bytes led by a NUL, so the classifier settles on binary at its
// probe instead of matching the generated header across megabytes.
func bulk(n int) string { return "\x00" + strings.Repeat("x", n-1) }

func TestWorktreeReadBound(t *testing.T) {
	t.Parallel()
	root := initRepo(t)
	write(t, root, "at.bin", bulk(model.MaxReadBytes))
	write(t, root, "over.bin", bulk(model.MaxReadBytes+1))
	repo, err := source.Discover(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	w, err := source.NewWorktree(t.Context(), repo)
	if err != nil {
		t.Fatal(err)
	}
	if got := mustRead(t, w, "at.bin"); len(got) != model.MaxReadBytes {
		t.Errorf("a file at the bound reads whole: %d bytes", len(got))
	}
	if err := readErr(w, "over.bin"); !errors.Is(err, model.ErrTooLarge) {
		t.Errorf("a file past the bound: %v, want ErrTooLarge", err)
	}
	sizes := map[string]int64{}
	for _, f := range w.Files() {
		sizes[f.Path] = f.Size
	}
	if sizes["at.bin"] != model.MaxReadBytes || sizes["over.bin"] != model.MaxReadBytes+1 {
		t.Errorf("sizes = %v", sizes)
	}
}

