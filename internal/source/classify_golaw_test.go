package source_test

import (
	"testing"

	"github.com/cristianargotti/golaw/internal/model"
	"github.com/cristianargotti/golaw/internal/source"
)

const golawHeader = "// Code generated by golaw 0.3.0 kind=adapter-sql@1; DO NOT EDIT.\n\npackage postgres\n"

func TestClassifyHoldsGolawGeneratedFilesToTheirPathClass(t *testing.T) {
	t.Parallel()
	tests := map[string]struct {
		path    string
		content string
		tracked bool
		want    model.FileClass
	}{
		"red: a tracked regenerable file is analysed code":    {path: "internal/adapters/out/postgres/zz_generated_plans.go", content: golawHeader, tracked: true, want: model.ClassTracked},
		"red: an untracked regenerable file is analysed code": {path: "internal/adapters/out/postgres/zz_generated_plans.go", content: golawHeader, want: model.ClassUntracked},
		"red: a regenerable test file is a test":              {path: "internal/adapters/out/postgres/zz_generated_plans_contract_test.go", content: golawHeader, tracked: true, want: model.ClassTest},
		"red: a regenerable file under testdata is a fixture": {path: "internal/gen/testdata/slice/zz_generated_plans.go", content: golawHeader, tracked: true, want: model.ClassFixture},
		"near: a third party header stays generated":          {path: "internal/adapters/out/postgres/sqlcgen/plans.sql.go", content: "// Code generated by sqlc. DO NOT EDIT.\npackage sqlcgen\n", tracked: true, want: model.ClassGenerated},
		"near: a golaw header on the second line stays generated": {
			path: "internal/x/x.go", content: "// Package x.\n// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\npackage x\n", tracked: true, want: model.ClassGenerated,
		},
		"near: a NUL byte stays binary": {path: "internal/x/zz_generated_x.go", content: golawHeader + "\x00", tracked: true, want: model.ClassBinary},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			if got := source.Classify(tc.path, []byte(tc.content), tc.tracked); got != tc.want {
				t.Errorf("Classify(%s) = %v, want %v", tc.path, got, tc.want)
			}
		})
	}
}
