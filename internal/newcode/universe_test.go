// universeTree holds one file per way a path enters or leaves the
// universe; sonar-project.properties names the generic exclusion.
func universeTree() *proof.Tree {
	return proof.NewTree(map[string][]byte{
		"go.mod":                         []byte("module example.test/sample\n\ngo 1.27\n"),
		"sonar-project.properties":       []byte("sonar.exclusions=integration/**\n"),
		"value.go":                       []byte("package sample\n"),
		"value_test.go":                  []byte("package sample\n"),
		"cmd/app/main.go":                []byte("package main\n"),
		"integration/flow.go":            []byte("package integration\n"),
		"internal/gen/api.go":            []byte("package gen\n"),
		"api.pb.go":                      []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage sample\n"),
		"testdata/fixture.go":            []byte("package fixture\n"),
		"vendor/example.test/dep/dep.go": []byte("package dep\n"),
		".tools/tool.go":                 []byte("package tools\n"),
		"_draft/a.go":                    []byte("package draft\n"),
		"nested/go.mod":                  []byte("module example.test/nested\n\ngo 1.27\n"),
		"nested/inner.go":                []byte("package nested\n"),
		"web/app.js":                     []byte("export const a = 1;\n"),
	})
}

func resolved(t *testing.T, in surface.ScopeInput) surface.Scope {
	t.Helper()
	scope, err := surface.Resolve(in)
	if err != nil {
		t.Fatal(err)
	}
	return scope
}

func analyzer(exclusions, coverageExclusions []string) model.AnalyzerPolicy {
	policy := model.DefaultSurface().Analyzer
	policy.Exclusions, policy.CoverageExclusions = exclusions, coverageExclusions
	return policy
}

func syntheticProfile(t *testing.T) *model.AnalyzerPolicy {
	t.Helper()
	config := t.TempDir()
	profiletest.SurfaceInstall(t, config)
	data, err := profile.Load(config, profiletest.SurfaceRef(t))
	if err != nil || data.Analyzer == nil {
		t.Fatalf("the synthetic profile = %+v, %v", data, err)
	}
	return data.Analyzer
}

func members(tree *proof.Tree, universe func(string) bool) []string {
	var out []string
	for _, file := range tree.Files() {
		if universe(file.Path) {
			out = append(out, file.Path)
		}
	}
	return out
}

func TestUniverseIsWhatThePipelineMeasures(t *testing.T) {
	t.Parallel()
	tree := universeTree()
	core := model.CoreDefaults()
	for _, tc := range []struct {
		name  string
		scope func(t *testing.T) surface.Scope
		want  []string
	}{
		{"red-no-source-the-whole-module-counts", func(t *testing.T) surface.Scope {
			t.Helper()
			return resolved(t, surface.ScopeInput{Policy: analyzer(nil, nil)})
		}, []string{"cmd/app/main.go", "integration/flow.go", "internal/gen/api.go", "value.go"}},
		{"near-golaw-yml-exclusions", func(t *testing.T) surface.Scope {
			t.Helper()
			return resolved(t, surface.ScopeInput{Policy: analyzer([]string{"integration/**"}, nil)})
		}, []string{"cmd/app/main.go", "internal/gen/api.go", "value.go"}},
		{"near-coverage-exclusions", func(t *testing.T) surface.Scope {
			t.Helper()
			return resolved(t, surface.ScopeInput{Policy: analyzer(nil, []string{"cmd/**"})})
		}, []string{"integration/flow.go", "internal/gen/api.go", "value.go"}},
		{"near-sonar-project-properties", func(t *testing.T) surface.Scope {
			t.Helper()
			scope, err := surface.ScopeOf(t.Context(), tree, &core)
			if err != nil || scope.Source != model.FromProperties {
				t.Fatalf("scope = %+v, %v", scope, err)
			}
			return scope
		}, []string{"cmd/app/main.go", "internal/gen/api.go", "value.go"}},
		{"near-the-synthetic-profile-wins-over-the-properties", func(t *testing.T) surface.Scope {
			t.Helper()
			props, err := tree.Read(surface.PropertiesFile)
			if err != nil {
				t.Fatal(err)
			}
			return resolved(t, surface.ScopeInput{
				Policy: analyzer(nil, nil), Profile: syntheticProfile(t), Profiled: profiletest.SurfaceRef(t).Name,
				Properties: props, HasProps: true,
			})
		}, []string{"cmd/app/main.go", "value.go"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if got := members(tree, newcode.Universe(tree, tc.scope(t))); !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("universe = %q, want %q", got, tc.want)
			}
		})
	}
}

func TestStaleReportIsOlderThanAGoFileInScope(t *testing.T) {
	t.Parallel()
	tree := universeTree()
	universe := newcode.Universe(tree, resolved(t, surface.ScopeInput{Policy: analyzer(nil, nil)}))
	report := time.Date(2026, time.October, 27, 10, 0, 0, 0, time.UTC)
	for _, tc := range []struct {
		name  string
		newer string
		stale bool
	}{
		{"near-every-file-at-the-report-time", "", false},
		{"red-a-source-in-scope-is-newer", "integration/flow.go", true},
		{"near-a-test-file-is-newer", "value_test.go", false},
		{"near-a-script-is-newer", "web/app.js", false},
		{"near-a-generated-file-is-newer", "api.pb.go", false},
		{"near-a-nested-module-is-newer", "nested/inner.go", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			modTime := func(path string) (time.Time, error) {
				if path == tc.newer {
					return report.Add(time.Second), nil
				}
				return report, nil
			}
			stale, err := newcode.Stale(report, tree, universe, modTime)
			if err != nil || stale != tc.stale {
				t.Fatalf("Stale = %v, %v, want %v", stale, err, tc.stale)
			}
		})
	}
}

func TestStaleNamesATimeItCannotRead(t *testing.T) {
	t.Parallel()
	tree := universeTree()
	universe := newcode.Universe(tree, resolved(t, surface.ScopeInput{Policy: analyzer(nil, nil)}))
	unreadable := func(string) (time.Time, error) { return time.Time{}, fs.ErrPermission }
	if _, err := newcode.Stale(time.Now(), tree, universe, unreadable); !errors.Is(err, newcode.ErrReport) || !errors.Is(err, fs.ErrPermission) {
		t.Fatalf("Stale = %v, want ErrReport carrying the cause", err)
	}
}
