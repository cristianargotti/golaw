package goast

import "testing"

// The check never judges a test file, so the test file rule of
// golawErrorsFile is held here, where its answer is observable.
func TestGolawErrorsFileNamesOnlyTheGeneratedErrorsSources(t *testing.T) {
	t.Parallel()
	header := []byte("// Code generated by golaw 0.3.0 kind=support@1; DO NOT EDIT.\n\npackage gensupport\n")
	tests := []struct {
		path string
		src  []byte
		want bool
	}{
		{"internal/gensupport/zz_generated_errors.go", header, true},
		{"internal/gensupport/zz_generated_errors_httpx.go", header, true},
		{"internal/gensupport/zz_generated_errors_httpx_test.go", header, false},
		{"internal/gensupport/zz_generated_errors_test.go", header, false},
		{"internal/gensupport/zz_generated_errorsx.go", header, false},
		{"internal/gensupport/zz_generated_errors_httpx.go", []byte("package gensupport\n"), false},
	}
	for _, tc := range tests {
		if got := golawErrorsFile(tc.path, tc.src); got != tc.want {
			t.Errorf("golawErrorsFile(%q) = %t, want %t", tc.path, got, tc.want)
		}
	}
}
