package goast_test

import (
	"strings"
	"testing"

	"github.com/cristianargotti/golaw/internal/checks/goast"
)

const golawHeader = "// Code generated by golaw 0.3.0 kind=support@1; DO NOT EDIT.\n\n"

const supportErrors = `package gensupport

import "errors"

// ErrStatus marks an answer whose status the caller did not expect.
var ErrStatus = errors.New("unexpected http status")
`

func TestSentinelDeclAcceptsTheGolawErrorsFiles(t *testing.T) {
	t.Parallel()
	sqltest := strings.Replace(supportErrors, "package gensupport", "package sqltest", 1)
	tests := []struct {
		name, path, src string
		codes           []string
	}{
		{"the support errors file", "internal/gensupport/zz_generated_errors.go", golawHeader + supportErrors, nil},
		{"the errors file of one support part", "internal/gensupport/zz_generated_errors_httpx.go", golawHeader + supportErrors, nil},
		{"the errors file of a support subpackage", "internal/gensupport/sqltest/zz_generated_errors.go", golawHeader + sqltest, nil},
		{"near: errors.go keeps passing", "internal/app/errors.go", supportErrors, nil},
		{"red: the name without the golaw header", "internal/gensupport/zz_generated_errors_httpx.go", supportErrors, []string{"sentinel-decl"}},
		{"red: a golaw file of another name", "internal/gensupport/zz_generated_httpx.go", golawHeader + supportErrors, []string{"sentinel-decl"}},
		{"red: the prefix without its separator", "internal/gensupport/zz_generated_errorsx.go", golawHeader + supportErrors, []string{"sentinel-decl"}},
		{"near: a golaw test file of the name is never judged", "internal/gensupport/zz_generated_errors_httpx_test.go", golawHeader + supportErrors, nil},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			res := scan(t, goast.SentinelDecl(), map[string]string{tc.path: tc.src})
			expectCodes(t, res, tc.codes...)
		})
	}
}
