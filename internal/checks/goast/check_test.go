func TestChecksCarryValidSpecs(t *testing.T) {
	t.Parallel()
	seen := map[string]bool{}
	for _, c := range goast.Checks() {
		s := c.Spec()
		if err := s.Validate(); err != nil {
			t.Error(err)
		}
		if seen[s.ID] {
			t.Errorf("%s is listed twice", s.ID)
		}
		seen[s.ID] = true
		if s.Proof != s.ID || s.Scope != model.ScopeFile || s.Owner != model.OwnerCore {
			t.Errorf("%s: proof, scope or owner is wrong: %+v", s.ID, s)
		}
		if s.Rule != "rules/4.3@1" || !slices.Contains(s.Needs, "go") {
			t.Errorf("%s: rule or needs are wrong: %+v", s.ID, s)
		}
	}
}

func TestRunJudgesOnlyGoSources(t *testing.T) {
	t.Parallel()
	long := "package a\n\n" + strings.Repeat("// line\n", 299)
	res := scan(t, goast.FileLength(), map[string]string{
		"docs/a.md":     long,
		"testdata/a.go": long,
		"gen.go":        "// Code generated by x. DO NOT EDIT.\n" + long,
		"a.go":          long,
		"a_test.go":     long,
		"bin.go":        "\x00" + long,
	})
	expectCodes(t, res, "file-length", "file-length")
	if res.Scope != "2 files" || res.Findings[0].Path != "a.go" || res.Findings[1].Path != "a_test.go" {
		t.Errorf("scope %q over %+v", res.Scope, res.Findings)
	}
}

func TestRunLeavesAnUnreadableTargetUnmeasured(t *testing.T) {
	t.Parallel()
	big := strings.Repeat("x", model.MaxReadBytes+1)
	expectUnmeasured(t, scan(t, goast.FileLength(), map[string]string{"a.go": big}), "read bound")
}

func TestRunFailsOnPassedDeadline(t *testing.T) {
	t.Parallel()
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	c := goast.FileLength()
	_, err := c.Run(ctx, input(c, map[string]string{"a.go": "package a\n"}))
	if !errors.Is(err, context.Canceled) || !strings.Contains(err.Error(), "goast.file-length: deadline") {
		t.Fatalf("Run on a passed deadline = %v", err)
	}
}
