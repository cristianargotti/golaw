package genguard

import (
	"path"
	"strings"

	"github.com/cristianargotti/golaw/internal/gen/manifest"
	"github.com/cristianargotti/golaw/internal/genheader"
	"github.com/cristianargotti/golaw/internal/model"
)

// The words of the reasons of M7.9.6; internal/report reads the same
// prefixes to write the person's sentence, so a change here changes both.
const (
	codeGeneratedWrite = "generated-write"
	golawFrom          = "is generated by golaw from "
	sqlcFrom           = "is generated by sqlc from "
	oapiFrom           = "is generated by oapi-codegen from "
	editContract       = ": edit the contract and the hook regenerates it, or run golaw gen."
)

// queriesDir is where the sqlc configuration the kit renders reads its
// queries, so a query output names the one file that produced it.
const queriesDir = "db/queries/"

// sqlcStem is the suffix sqlc gives the output of one query file.
const sqlcStem = ".sql.go"

// generatedReason answers why file is generated and what to edit instead,
// or false when the kit cannot name the contract: the output of a
// generator golaw does not know is left to the pipeline, because a denial
// must name the file that fixes it (reading 1).
func generatedReason(file string, base []byte, known *manifest.Manifest, g model.GeneratePolicy, exists func(string) bool) (string, bool) {
	if known != nil {
		if e, ok := known.Regenerable(file); ok {
			return entryReason(e), true
		}
	}
	if !genheader.Convention(base) {
		return "", false
	}
	if h, ok := genheader.Parse(base); ok {
		// A golaw file a readable manifest does not list is an orphan:
		// golaw gen neither rewrites nor removes it, so a denial would name
		// no fix and the agent could never delete it.
		if known != nil {
			return "", false
		}
		return "is generated by golaw (" + h.Ref() + "): run golaw gen.", true
	}
	if under(file, g.ThirdParty.SQLCOut) {
		return sqlcReason(file, exists), true
	}
	if under(file, g.ThirdParty.OpenAPIOut) {
		return oapiFrom + g.ThirdParty.OpenAPI + ": edit the document and run golaw gen.", true
	}
	return "", false
}

// under reports whether file lies inside dir; an empty dir holds nothing.
func under(file, dir string) bool {
	return dir != "" && strings.HasPrefix(file, dir+"/")
}

// entryReason names the contract of a manifest entry; a use case has none
// but its own entry (M7.3.1), so its reason names the command that wrote it.
func entryReason(e manifest.Entry) string {
	if len(e.Contracts) == 0 {
		return golawFrom + "the manifest entry " + e.Kind + " " + e.Name + ": rerun golaw new " + e.Kind + " " + e.Name + " with its flags, or run golaw gen."
	}
	c := e.Contracts[0]
	label := ""
	if c.Symbol != "" {
		label = " (port " + c.Symbol + ")"
	}
	return golawFrom + c.Path + label + editContract
}

// sqlcReason names the query file of the same stem when the base holds it,
// else the schema and queries sqlc.yaml names, which render models.go,
// db.go and querier.go together.
func sqlcReason(file string, exists func(string) bool) string {
	if stem, ok := strings.CutSuffix(path.Base(file), sqlcStem); ok {
		if query := queriesDir + stem + ".sql"; exists(query) {
			return sqlcFrom + query + ": edit the query and run golaw gen."
		}
	}
	return sqlcFrom + "the schema and queries sqlc.yaml names: edit them and run golaw gen."
}
