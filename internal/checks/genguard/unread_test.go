// failingTree is a fixture tree whose reads of some paths fail with a
// given error, the way a worktree answers a file over the read bound or
// one it cannot open.
type failingTree struct {
	*proof.Tree

	fail map[string]error
}

func (f failingTree) Read(path string) ([]byte, error) {
	if err, ok := f.fail[path]; ok {
		return nil, err
	}
	return f.Tree.Read(path) //nolint:wrapcheck // the tree's own sentinel is what the check reads
}

func TestGeneratedWriteLeavesABaseItCannotReadUnreadUnlessTheManifestNamesIt(t *testing.T) {
	t.Parallel()
	const big, locked = "internal/a/big.go", "internal/a/locked.go"
	tree := failingTree{
		Tree: proof.NewTree(map[string][]byte{manifest.Path: []byte(manifestYAML(t)), big: nil, locked: nil, fakePath: nil}),
		fail: map[string]error{big: model.ErrTooLarge, locked: model.ErrUnreadable, fakePath: model.ErrTooLarge},
	}
	event := &model.Event{Shape: model.ShapeWrite, Agent: "tester", Tool: "Write", Candidates: []model.Candidate{
		{Path: big, Op: model.CandidateReplace, Reconstructed: true},
		{Path: locked, Op: model.CandidateReplace, Reconstructed: true},
		{Path: fakePath, Op: model.CandidateReplace, Reconstructed: true},
	}}
	res, err := genguard.GeneratedWrite().Run(t.Context(), model.Input{Mode: model.ModeHook, Policy: proof.Policy(), Snapshot: tree, Event: event})
	if err != nil || res.Status.Kind != model.Measured().Kind {
		t.Fatalf("res = %+v, err = %v", res, err)
	}
	if !slices.Equal(res.Unread, []string{big, locked}) {
		t.Errorf("unread = %v, want the two files no rule names", res.Unread)
	}
	if len(res.Findings) != 1 || res.Findings[0].Path != fakePath || res.Findings[0].Message != "is generated by golaw from "+portsPath+" (port Ledger)"+editPortTail {
		t.Errorf("findings = %+v, want the regenerable file denied by its name", res.Findings)
	}
}

func TestGenFamilyListsBothDenials(t *testing.T) {
	t.Parallel()
	checks := genguard.Checks()
	ids := make([]string, 0, len(checks))
	for _, c := range checks {
		ids = append(ids, c.Spec().ID)
	}
	if !slices.Equal(ids, []string{"gen.generated-write", "gen.manifest-write", "gen.handwritten-reason", "gen.handwritten"}) {
		t.Errorf("Checks() = %v", ids)
	}
	in := model.Input{Mode: model.ModeScan, Policy: proof.Policy(), Snapshot: proof.NewTree(nil)}
	if res, err := genguard.ManifestWrite().Run(t.Context(), in); err != nil || res.Status.Kind != model.StatusNotApplicable {
		t.Errorf("a scan: res = %+v, err = %v", res, err)
	}
}
