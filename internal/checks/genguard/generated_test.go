const (
	portsPath    = "internal/application/growth/ports.go"
	fakePath     = "internal/application/growth/ledgertest/zz_generated_fake.go"
	casesPath    = "internal/application/growth/ledgertest/cases.go"
	usecasesPath = "internal/application/growth/zz_generated_usecases.go"
	readPlanPath = "internal/application/growth/read_plan.go"
	golawHeader  = "// Code generated by golaw 0.3.0 kind=port@1; DO NOT EDIT.\n\npackage ledgertest\n"
	sqlcHeader   = "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.31.1\n\npackage sqlcgen\n"
	oapiHeader   = "//go:build go1.22\n\n// Package apigen provides primitives.\n//\n// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.8.0 DO NOT EDIT.\npackage apigen\n"
	editPortTail = ": edit the contract and the hook regenerates it, or run golaw gen."
	orphanPath   = "internal/old/zz_generated_fake.go"
)

// manifestYAML is a manifest with a port entry and a use case entry, the
// shapes M7.6.1 records, written by the package's own encoder.
func manifestYAML(t *testing.T) string {
	t.Helper()
	m := manifest.Manifest{
		Schema:  manifest.Schema,
		Support: manifest.Support{Path: "internal/gensupport", Template: "support@1"},
		Entries: []manifest.Entry{
			{
				Kind: genkind.KindPort, Template: "port@1", Name: "growth.Ledger",
				Contracts:   []manifest.Contract{{Path: portsPath, Symbol: "Ledger"}},
				Regenerable: []string{fakePath}, Owned: []string{casesPath},
			},
			{
				Kind: genkind.KindUsecase, Template: "usecase@1", Name: "growth.ReadPlan",
				Ports: []string{"Ledger"}, In: "ReadPlanInput", Out: "Plan",
				Regenerable: []string{usecasesPath}, Owned: []string{readPlanPath},
			},
		},
	}
	data, err := m.Encode()
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

type writeCase struct {
	base    map[string]string
	op      model.CandidateOp
	path    string
	from    string
	content string
	want    string // the finding message, empty for none
	where   string // the finding path when it is not path
}

// judge runs the check the way the hook does: the candidate folded over the
// base through the source overlay, so the snapshot keeps its base.
func judge(t *testing.T, tc writeCase) model.Result {
	t.Helper()
	base := map[string][]byte{}
	for p, text := range tc.base {
		base[p] = []byte(text)
	}
	candidate := model.Candidate{Path: tc.path, Op: tc.op, From: tc.from, Reconstructed: true}
	content := map[string][]byte{}
	if tc.op != model.CandidateDelete {
		content[tc.path] = []byte(tc.content)
	}
	overlay, candidates, err := source.NewOverlay(proof.NewTree(base), source.FromCandidates([]model.Candidate{candidate}, content))
	if err != nil {
		t.Fatal(err)
	}
	event := &model.Event{Shape: model.ShapeWrite, Agent: "tester", Tool: "Write", Candidates: candidates}
	res, err := genguard.GeneratedWrite().Run(t.Context(), model.Input{Mode: model.ModeHook, Policy: proof.Policy(), Snapshot: overlay, Event: event})
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func TestGeneratedWriteDeniesWhatItRecognizesAndNamesTheContract(t *testing.T) {
	t.Parallel()
	gen := manifestYAML(t)
	tests := map[string]writeCase{
		"red: a write over a golaw regenerable file": {
			base: map[string]string{manifest.Path: gen, fakePath: golawHeader}, op: model.CandidateReplace, path: fakePath, content: "package ledgertest\n",
			want: "is generated by golaw from " + portsPath + " (port Ledger)" + editPortTail,
		},
		"red: an edit that strips the header": {
			base: map[string]string{manifest.Path: gen, fakePath: golawHeader}, op: model.CandidateEdit, path: fakePath, content: "\npackage ledgertest\n",
			want: "is generated by golaw from " + portsPath + " (port Ledger)" + editPortTail,
		},
		"red: recreating a regenerable path the manifest lists": {
			base: map[string]string{manifest.Path: gen}, op: model.CandidateCreate, path: fakePath, content: "package ledgertest\n",
			want: "is generated by golaw from " + portsPath + " (port Ledger)" + editPortTail,
		},
		"red: the regenerable file of a use case entry": {
			base: map[string]string{manifest.Path: gen, usecasesPath: golawHeader}, op: model.CandidateReplace, path: usecasesPath, content: "package growth\n",
			want: "is generated by golaw from the manifest entry usecase growth.ReadPlan: rerun golaw new usecase growth.ReadPlan with its flags, or run golaw gen.",
		},
		"red: a golaw file without a manifest": {
			base: map[string]string{fakePath: golawHeader}, op: model.CandidateDelete, path: fakePath,
			want: "is generated by golaw (port@1): run golaw gen.",
		},
		"red: a move away from a generated file": {
			base: map[string]string{fakePath: golawHeader}, op: model.CandidateMove, path: "internal/application/growth/ledgertest/fake.go", from: fakePath, content: golawHeader,
			want: "is generated by golaw (port@1): run golaw gen.", where: fakePath,
		},
		"red: an sqlc query output": {
			base: map[string]string{"db/queries/plans.sql": "-- name: ReadPlan :one\nSELECT 1;\n", "internal/adapters/out/postgres/sqlcgen/plans.sql.go": sqlcHeader},
			op:   model.CandidateReplace, path: "internal/adapters/out/postgres/sqlcgen/plans.sql.go", content: "package sqlcgen\n",
			want: "is generated by sqlc from db/queries/plans.sql: edit the query and run golaw gen.",
		},
		"red: the sqlc models file": {
			base: map[string]string{"internal/adapters/out/postgres/sqlcgen/models.go": sqlcHeader},
			op:   model.CandidateReplace, path: "internal/adapters/out/postgres/sqlcgen/models.go", content: "package sqlcgen\n",
			want: "is generated by sqlc from the schema and queries sqlc.yaml names: edit them and run golaw gen.",
		},
		"red: an oapi-codegen output": {
			base: map[string]string{"api/gen/server.gen.go": oapiHeader}, op: model.CandidateReplace, path: "api/gen/server.gen.go", content: "package apigen\n",
			want: "is generated by oapi-codegen from api/openapi.yaml: edit the document and run golaw gen.",
		},
		"near: a hand written file that quotes the header in its body": {
			base: map[string]string{"internal/application/growth/notes.go": "package growth\n\nconst header = `\n" + golawHeader + "`\n"},
			op:   model.CandidateReplace, path: "internal/application/growth/notes.go", content: "package growth\n",
		},
		"near: the owned file of the same entry": {
			base: map[string]string{manifest.Path: gen, fakePath: golawHeader, casesPath: "package ledgertest\n"},
			op:   model.CandidateReplace, path: casesPath, content: "package ledgertest\n\nconst version = 1\n",
		},
		"near: the delete of a golaw file no entry of the manifest lists": {
			base: map[string]string{manifest.Path: gen, orphanPath: golawHeader}, op: model.CandidateDelete, path: orphanPath,
		},
		"near: the move of a golaw file no entry of the manifest lists": {
			base: map[string]string{manifest.Path: gen, orphanPath: golawHeader}, op: model.CandidateMove, path: "internal/old/fake.go", from: orphanPath, content: golawHeader,
		},
		"near: a generated file of a generator golaw does not know": {
			base: map[string]string{"internal/mocks/ledger.go": "// Code generated by MockGen. DO NOT EDIT.\npackage mocks\n"},
			op:   model.CandidateReplace, path: "internal/mocks/ledger.go", content: "package mocks\n",
		},
		"near: a manifest that does not decode leaves the header rule alone": {
			base: map[string]string{manifest.Path: "golaw-gen: 9\n", "internal/application/growth/plan.go": "package growth\n"},
			op:   model.CandidateReplace, path: "internal/application/growth/plan.go", content: "package growth\n",
		},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			wantGenerated(t, tc, judge(t, tc))
		})
	}
}

// wantGenerated holds a result to the case: measured, and no finding for a
// near miss or the one denial at the path the case names.
func wantGenerated(t *testing.T, tc writeCase, res model.Result) {
	t.Helper()
	if res.Status.Kind != model.Measured().Kind {
		t.Fatalf("status = %+v", res.Status)
	}
	if tc.want == "" {
		if len(res.Findings) != 0 {
			t.Fatalf("findings = %+v, want none", res.Findings)
		}
		return
	}
	where := tc.path
	if tc.where != "" {
		where = tc.where
	}
	if len(res.Findings) != 1 {
		t.Fatalf("findings = %+v, want one", res.Findings)
	}
	f := res.Findings[0]
	if f.Code != "generated-write" || f.Path != where || f.Message != tc.want || f.Severity != model.SeverityDeny {
		t.Errorf("finding = %+v\nwant %s %q", f, where, tc.want)
	}
}

func TestGeneratedWriteReadsAFixtureTreeAsTheBase(t *testing.T) {
	t.Parallel()
	tree := proof.NewTree(map[string][]byte{fakePath: []byte(golawHeader)})
	event := &model.Event{Shape: model.ShapeWrite, Agent: "tester", Tool: "Write", Candidates: []model.Candidate{{Path: fakePath, Op: model.CandidateReplace, Reconstructed: true}}}
	res, err := genguard.GeneratedWrite().Run(t.Context(), model.Input{Mode: model.ModeHook, Policy: proof.Policy(), Snapshot: tree, Event: event})
	if err != nil || len(res.Findings) != 1 {
		t.Fatalf("res = %+v, err = %v", res, err)
	}
}

func TestGeneratedWriteJudgesOnlyAnAgentWriteInTheHook(t *testing.T) {
	t.Parallel()
	tree := proof.NewTree(map[string][]byte{fakePath: []byte(golawHeader)})
	read := &model.Event{Shape: model.ShapeRead, Agent: "tester", Tool: "Read", Read: &model.ReadRequest{Path: fakePath}}
	for name, in := range map[string]model.Input{
		"a read event": {Mode: model.ModeHook, Policy: proof.Policy(), Snapshot: tree, Event: read},
		"a scan":       {Mode: model.ModeScan, Policy: proof.Policy(), Snapshot: tree},
	} {
		res, err := genguard.GeneratedWrite().Run(t.Context(), in)
		if err != nil || res.Status.Kind != model.NotApplicable("").Kind {
			t.Errorf("%s: res = %+v, err = %v", name, res, err)
		}
	}
}
