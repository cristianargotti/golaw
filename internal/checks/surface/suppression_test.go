// marker is the Sonar suppression marker the check refuses.
const marker = "NO" + "SONAR"

func TestSuppressionFindsTheMarkerAndTheBareSuppressions(t *testing.T) {
	t.Parallel()
	runCases(t, surface.Suppression(), []fileCase{
		{"the marker in a script comment", "views/common.js", lines(7, "run();") + "done(); // " + marker + "\n", []string{"views/common.js:8 suppression"}},
		{"the marker in a block comment", "a.ts", "/* " + marker + " */\n", []string{"a.ts:1 suppression"}},
		{"the marker in an html script", "views/a.html", "<script>\nrun(); // " + marker + "\n</script>\n", []string{"views/a.html:2 suppression"}},
		{"the marker in an html comment", "views/a.html", "<p>x</p> <!-- " + marker + " -->\n", []string{"views/a.html:1 suppression"}},
		{"the marker in a style sheet", "views/a.css", "a { color: red; } /* " + marker + " */\n", []string{"views/a.css:1 suppression"}},
		{"the marker in a style block", "views/b.html", "<style>\na { color: red; } /* " + marker + " */\n</style>\n", []string{"views/b.html:2 suppression"}},
		{"the marker in a python comment", "a.py", "x = 1  # " + marker + "\n", []string{"a.py:1 suppression"}},
		{"the marker in a go comment", "internal/a/a.go", "package a\n\nfunc f() {} // " + marker + "\n", []string{"internal/a/a.go:3 suppression"}},
		{"the marker in a go test", "internal/a/a_test.go", "package a\n\n// " + marker + "\nfunc g() {}\n", []string{"internal/a/a_test.go:3 suppression"}},
		{"the marker in a shell comment", "scripts/up.sh", "#!/bin/sh\n# " + marker + "\nrun\n", []string{"scripts/up.sh:2 suppression"}},
		{"the marker in a Dockerfile comment", "Dockerfile", "FROM scratch\n# " + marker + "\n", []string{"Dockerfile:2 suppression"}},
		{"the marker in a yaml comment", "deploy/compose.yaml", "services: {}\n# " + marker + "\n", []string{"deploy/compose.yaml:2 suppression"}},
		{"a bare eslint-disable-next-line", "a.js", "// eslint-disable-next-line\nrun();\n", []string{"a.js:1 suppression"}},
		{"a bare eslint-disable-line", "a.js", "run(); // eslint-disable-line\n", []string{"a.js:1 suppression"}},
		{"a bare block eslint-disable", "a.jsx", "/* eslint-disable */\n", []string{"a.jsx:1 suppression"}},
		{"a bare noqa", "a.py", "import os  # noqa\n", []string{"a.py:1 suppression"}},
		{"an upper case bare noqa", "a.py", "import os  # NOQA\n", []string{"a.py:1 suppression"}},
		{"a bare type ignore", "a.py", "x = f()  # type: ignore\n", []string{"a.py:1 suppression"}},
		{"a bare pyright ignore", "a.py", "x = f()  # pyright: ignore\n", []string{"a.py:1 suppression"}},
	})
}

func TestSuppressionLeavesTheNearMissesAlone(t *testing.T) {
	t.Parallel()
	runCases(t, surface.Suppression(), []fileCase{
		{"the marker in a script string", "a.js", "const s = \"" + marker + "\";\n", nil},
		{"the marker in a go string", "a.go", "package a\n\nconst s = \"" + marker + "\"\n", nil},
		{"the marker in a python string", "a.py", "s = \"# " + marker + "\"\n", nil},
		{"a shell line that is no comment", "scripts/up.sh", "echo \"# " + marker + "\"\n", nil},
		{"a rule and a reason", "a.js", "// eslint-disable-next-line no-console -- the command prints\nconsole.log(x);\n", nil},
		{"a rule list", "a.js", "/* eslint-disable no-console */\n", nil},
		{"eslint-enable", "a.js", "/* eslint-enable */\n", nil},
		{"prose about a directive", "a.js", "// the team never writes eslint-disable here\n", nil},
		{"a noqa with codes", "a.py", "import os  # noqa: F401\n", nil},
		{"a type ignore with a rule", "a.py", "x = f()  # type: ignore[attr-defined]\n", nil},
		{"a pyright ignore with a rule", "a.py", "x = f()  # pyright: ignore[reportAttributeAccessIssue]\n", nil},
		{"a generated go file", "gen.go", "// Code generated by tool. DO NOT EDIT.\n\npackage a // " + marker + "\n", nil},
		{"a fixture", "pkg/testdata/a.js", "// " + marker + "\n", nil},
	})
}

func TestSuppressionNamesTheMarker(t *testing.T) {
	t.Parallel()
	res := scanFiles(t, surface.Suppression(), map[string]string{
		"a.js": "run(); // " + marker + "\n// eslint-disable-next-line\nrun();\n",
		"b.py": "import os  # noqa\nx = f()  # type: ignore\n",
	})
	want := []model.Finding{
		{Path: "a.js", Line: 1, Code: "suppression", Severity: model.SeverityDeny, Message: "adds " + marker + ", which hides every rule on the line from the pipeline's analyzer: fix the finding; golaw lint names it."},
		{Path: "a.js", Line: 2, Code: "suppression", Severity: model.SeverityDeny, Message: "adds a bare eslint-disable-next-line, which hides every rule it reaches: name the rule and a reason after --, or fix the finding; golaw lint names it."},
		{Path: "b.py", Line: 1, Code: "suppression", Severity: model.SeverityDeny, Message: "adds a bare noqa, which hides every rule on the line: name the codes after noqa:, or fix the finding; golaw lint names it."},
		{Path: "b.py", Line: 2, Code: "suppression", Severity: model.SeverityDeny, Message: "adds a bare type: ignore, which hides every type error on the line: name the rule in brackets, or fix the error; golaw lint names it."},
	}
	if !slices.EqualFunc(res.Findings, want, sameFinding) {
		t.Fatalf("findings = %+v\nwant %+v", res.Findings, want)
	}
}

func TestSuppressionDeniesOnlyANewMarker(t *testing.T) {
	t.Parallel()
	c := surface.Suppression()
	legacy := map[string]string{"a.js": "run(); // " + marker + "\n"}
	expectFound(t, run(t, c, writeInput(c, legacy, map[string]string{"a.js": "start();\nrun(); // " + marker + "\n"})))
	expectFound(t, run(t, c, writeInput(c, legacy, map[string]string{"a.js": "run(); // " + marker + "\nstop(); // " + marker + "\n"})), "a.js:2 suppression")
}
